fit <- lm(mpg ~ wt, data = mtcars)
d <- diagData(fit)
stopifnot(identical(names(d), c("fitted", "resid", "std_resid")), nrow(d) == 32L)
stopifnot(isTRUE(all.equal(d$std_resid, unname(rstandard(fit)), check.attributes = FALSE)))
grDevices::pdf(NULL)
stopifnot(identical(plotResidFitted(fit), d))
stopifnot(identical(plotResidQQ(fit), d))
stopifnot(identical(plotScaleLocation(fit), d))
stopifnot(identical(plotResidHist(fit), d))
stopifnot(identical(plotDiagnostics(fit, title = "mpg ~ wt"), d))
grDevices::dev.off()
png_path <- tempfile(fileext = ".png")
stopifnot(identical(saveDiagnostics(fit, png_path), png_path), file.exists(png_path))
