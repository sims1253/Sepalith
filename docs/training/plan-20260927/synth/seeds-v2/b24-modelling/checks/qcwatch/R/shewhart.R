stopifnot(inherits(xb, "qc_shewhart"), identical(xb$stat, c(2, 3, 4, NA)), xb$center == 3)
stopifnot(isTRUE(all.equal(xb$sigma, 2 / 1.693)), xb$k == 3, length(xb$signals) == 0)
xk <- xbar.limits(x, sigma = 1, k = 2)
stopifnot(isTRUE(all.equal(xk$ucl[1], 3 + 2 / sqrt(3))), xk$k == 2)

