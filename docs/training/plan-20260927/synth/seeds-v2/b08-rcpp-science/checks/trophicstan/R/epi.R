ar <- attack.rate(20, 200)
stopifnot(identical(names(ar), c("estimate", "lower", "upper")), all.equal(ar$estimate, 0.1))
stopifnot(ar$lower < 0.1, ar$upper > 0.1)
stopifnot(inherits(try(attack.rate(5, 4), silent = TRUE), "try-error"))
cfr <- case.fatality.ratio(c(1, 3), c(10, 30))
