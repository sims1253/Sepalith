cl <- eoq.model(1000, 50, 1)
stopifnot(isTRUE(all.equal(cl$q, sqrt(1e5))), isTRUE(all.equal(cl$cost, sqrt(1e5))))
stopifnot(identical(names(cl), c("q", "orders", "cycle", "cost")))
stopifnot(isTRUE(all.equal(cl$cycle, 1 / cl$orders)))
bo <- eoq.model(1000, 50, 1, "backorder", shortage = 1)
stopifnot(isTRUE(all.equal(bo$q, sqrt(2e5))), bo$cost < cl$cost)
pr <- eoq.model(1000, 50, 1, "production", production.rate = 2000)
stopifnot(isTRUE(all.equal(pr$q, sqrt(2e5))), isTRUE(all.equal(pr$orders, 1000 / sqrt(2e5))))
br <- data.frame(min.qty = c(0, 500), price = c(10, 9))
ds <- eoq.model(1000, 50, 0.2, "discount", breaks = br)
stopifnot(ds$q == 500, isTRUE(all.equal(ds$cost, 2 * 50 + 250 * 0.2 * 9 + 9000)))
ds2 <- eoq.model(1000, 50, 0.2, "discount", breaks = data.frame(min.qty = c(0, 5000),
  price = c(10, 9.9)))
stopifnot(isTRUE(all.equal(ds2$q, sqrt(2 * 1000 * 50 / 2))))

tc <- total.cost.curve(c(100, 200, 400), 1000, 50, 1, unit.cost = 2)
stopifnot(identical(tc$ordering, c(500, 250, 125)), identical(tc$holding, c(50, 100, 200)))
stopifnot(all(tc$purchase == 2000), identical(tc$total, c(2550, 2350, 2325)))
stopifnot(attr(tc, "best") == 400, attr(total.cost.curve(c(100, 300), 1000, 50, 1), "best") == 300)
stopifnot(inherits(try(total.cost.curve(0, 1, 1, 1), silent = TRUE), "try-error"))

se <- eoq.sensitivity(1000, 50, 1, change = c(-0.5, 0, 1))
stopifnot(identical(se$input, rep(c("demand", "ordering", "holding"), each = 3)))
stopifnot(isTRUE(all.equal(se$q[3], sqrt(2e5))), isTRUE(all.equal(se$q[6], sqrt(2e5))))
stopifnot(isTRUE(all.equal(se$q[9], sqrt(5e4))), all(se$cost.change[c(2, 5, 8)] == 0))
stopifnot(isTRUE(all.equal(se$cost.change[1], sqrt(0.5) - 1)))

