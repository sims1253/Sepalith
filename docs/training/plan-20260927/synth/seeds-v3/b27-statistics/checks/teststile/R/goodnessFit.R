set.seed(51)
d = data.frame(x = stats::rnorm(60), z = stats::rnorm(60))
d$y = 2 + 3 * d$x + stats::rnorm(60)
f1 = stats::lm(y ~ x, data = d)
f2 = stats::lm(y ~ x + z, data = d)
ic = infoCriteria(f1)
stopifnot(all.equal(ic$aic, stats::AIC(f1)), all.equal(ic$bic, stats::BIC(f1)), ic$df == 3)
stopifnot(all.equal(ic$aicc, ic$aic + 24 / 56), ic$nobs == 60)

cm = compareModels(list(small = f1, big = f2))
stopifnot(setequal(cm$model, c("small", "big")), cm$delta[1] == 0, all.equal(sum(cm$weight), 1))
cmb = compareModels(list(f1, f2), "bic")
stopifnot(cmb$model[1] == "model1", all(diff(cmb$bic) >= 0))
stopifnot(all(diff(compareModels(list(f1, f2), "aicc")$aicc) >= 0))

