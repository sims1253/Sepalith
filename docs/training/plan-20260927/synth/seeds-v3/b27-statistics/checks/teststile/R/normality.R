sk = c(1, 2, 3, 4, 20)
g1 = sampleSkewness(sk)
stopifnot(g1 > 0, abs(sampleSkewness(c(1, 2, 3))) < 1e-12)
stopifnot(all.equal(sampleSkewness(sk, "G1"), g1 * sqrt(20) / 3))
stopifnot(all.equal(sampleSkewness(sk, "b1"), g1 * 0.8^1.5))

g2 = sampleKurtosis(sk)
stopifnot(all.equal(g2, mean((sk - 6)^4) / mean((sk - 6)^2)^2 - 3))
stopifnot(all.equal(sampleKurtosis(sk, "G2"), (6 * g2 + 6) * 4 / 6))
stopifnot(all.equal(sampleKurtosis(sk, "b2"), (g2 + 3) * 0.64 - 3))

set.seed(31)
zn = stats::rnorm(200)
ze = stats::rexp(200)
jb = jarqueBera(zn)
stopifnot(jb$parameter == 2, jb$pValue > 0.01, jarqueBera(ze)$pValue < 0.001, jb$method == "jb")

ad = andersonDarling(zn)
stopifnot(ad$statistic > 0, ad$pValue > 0.01, andersonDarling(ze)$pValue < 0.001)
stopifnot(all.equal(ad$parameter, ad$statistic * (1 + 0.75 / 200 + 2.25 / 200^2)))
stopifnot(inherits(try(andersonDarling(1:5), silent = TRUE), "try-error"))

dg = dagostinoTests(zn)
de = dagostinoTests(ze)
stopifnot(dg$pValue > 0.01, de$pValue < 0.001, de$skewZ > 0, de$skewP < 0.001)
stopifnot(all.equal(dg$omnibus, dg$skewZ^2 + dg$kurtZ^2), dg$kurtP > 0, dg$kurtP <= 1)
stopifnot(dagostinoTests(stats::runif(500))$kurtZ < -2)
stopifnot(inherits(try(dagostinoTests(1:10), silent = TRUE), "try-error"))

nt = normalityTable(data.frame(a = zn, b = ze, c = c(1:5, rep(NA, 195))))
stopifnot(identical(nt$n, c(200L, 200L, 5L)), nt$jbP[2] < 0.001, is.na(nt$adP[3]))
stopifnot(all.equal(nt$swStat[1], unname(stats::shapiro.test(zn)$statistic)))

ov = c(1, 2, 3, 2, 1, 2, 3, 2, 50, NA)
stopifnot(identical(outlierFlags(ov, threshold = 2)[9:10], c(TRUE, NA)))
stopifnot(sum(outlierFlags(ov, "modified"), na.rm = TRUE) == 1L)
stopifnot(which(outlierFlags(ov, "iqr")) == 9L)
stopifnot(!any(outlierFlags(c(1, 2, 3, 4), "iqr")))
stopifnot(sum(outlierFlags(1:100, "percentile", 0.05)) == 10L)
stopifnot(!outlierFlags(1:100, "percentile")[50])
stopifnot(inherits(try(normalityTable(data.frame(a = 1), "zz"), silent = TRUE), "try-error"))
