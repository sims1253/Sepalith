set.seed(11)
v <- stats::rnorm(60, 10, 2)
bb <- boot.bias.se(v, R = 400L, seed = 2)
stopifnot(bb$estimate == mean(v), abs(bb$bias) < 0.2, abs(bb$se - 2 / sqrt(60)) < 0.1)
stopifnot(all.equal(bb$corrected, bb$estimate - bb$bias))

cp <- boot.ci(v, R = 400L, seed = 3)
stopifnot(cp[["lower"]] < mean(v), cp[["upper"]] > mean(v), names(cp)[1] == "estimate")
cb <- boot.ci(v, R = 400L, type = "basic", seed = 3)
stopifnot(all.equal(cb[["lower"]] + cp[["upper"]], 2 * mean(v)))
cn <- boot.ci(v, R = 400L, type = "normal", seed = 3)
stopifnot(abs((cn[["upper"]] - cn[["lower"]]) - 2 * 1.96 * 2 / sqrt(60)) < 0.3)
ca <- boot.ci(v, stat = stats::median, R = 400L, type = "bca", seed = 3)
stopifnot(ca[["lower"]] < ca[["upper"]], ca[["estimate"]] == stats::median(v))

