stopifnot(all.equal(ls$trimmed.se, loc.se(z, "trimmed", trim = 0.2)), ls$huber.iter >= 1L)
stopifnot(ls$winsorized == loc.estimate(z, "winsorized", trim = 0.2), ls$hl == hodges.lehmann(z))
stopifnot(all.equal(ls$median.se, loc.se(z, "median")), ls$mean.se > 0)
stopifnot(inherits(try(loc.summary(1:2), silent = TRUE), "try-error"))
