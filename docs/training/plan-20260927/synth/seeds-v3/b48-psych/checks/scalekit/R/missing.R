stopifnot(identical(scorable(s, it, "half"), c(TRUE, TRUE, FALSE, TRUE)))
stopifnot(identical(scorable(s, it, "majority"), c(TRUE, FALSE, FALSE, TRUE)))
stopifnot(identical(scorable(s, it, "count"), c(TRUE, FALSE, FALSE, TRUE)))
stopifnot(identical(scorable(s, it, "any"), c(TRUE, TRUE, FALSE, TRUE)))
stopifnot(inherits(try(scorable(s, it, "count", -1), silent = TRUE), "try-error"))
