d <- data.frame(a = c(1, -9, -8, NA), b = c(-7, -6, 2, -9), id = c("x", "y", "z", "w"))
r <- recode_missing(d)
stopifnot(identical(r$a, c(1, NA, NA, NA)), identical(r$b, c(NA, NA, 2, NA)))
stopifnot(identical(r$id, d$id))
stopifnot(identical(attr(r, "codes"), c(refused = 2, dont_know = 1, not_applicable = 1,
  skipped = 1)))
r2 <- recode_missing(data.frame(a = c(99, 98, 97, 96)), 99, 98, 97, 96)
stopifnot(all(is.na(r2$a)), all(attr(r2, "codes") == 1))

m <- data.frame(a = c(1, NA, 3), b = c(3, 4, NA), c = c(NA, NA, NA))
pm <- impute_items(m, c("a", "b"), "person_mean")
stopifnot(identical(pm$a, c(1, 4, 3)), identical(pm$b, c(3, 4, 3)), attr(pm, "n_imputed") == 2)
im <- impute_items(m, c("a", "b"), "item_mean")
stopifnot(identical(im$a, c(1, 2, 3)), identical(im$b, c(3, 4, 3.5)))
id <- impute_items(m, c("a", "b", "c"), "item_median")
stopifnot(identical(id$a, c(1, 2, 3)), all(is.na(id$c)), attr(id, "n_imputed") == 2)
stopifnot(identical(impute_items(m, "c", "midpoint")$c, c(3, 3, 3)))
stopifnot(identical(impute_items(m, "a", "zero")$a, c(1, 0, 3)))

f <- data.frame(d1 = c(1, NA), d2 = c(NA, NA), a1 = c(1, 1), s1 = c(NA, 2), s2 = c(1, 2))
fm <- flag_missing(f, c("d1", "d2"), "a1", c("s1", "s2"))
stopifnot(identical(fm$depression_missing, c(1, 2)))
stopifnot(identical(fm$depression_valid, c(TRUE, FALSE)))
stopifnot(identical(fm$anxiety_valid, c(TRUE, TRUE)), identical(fm$stress_missing, c(1, 0)))
stopifnot(identical(fm$all_valid, c(TRUE, FALSE)))
stopifnot(identical(flag_missing(f, "d1", "a1", "s1", max_missing = 0)$all_valid, c(FALSE, FALSE)))
stopifnot(inherits(try(flag_missing(f, "q", "a1", "s1"), silent = TRUE), "try-error"))
stopifnot(inherits(try(flag_missing(f, "d1", "q", "s1"), silent = TRUE), "try-error"))
stopifnot(inherits(try(flag_missing(f, "d1", "a1", "q"), silent = TRUE), "try-error"))
stopifnot(inherits(try(flag_missing(f, "d1", "a1", "s1", -1), silent = TRUE), "try-error"))

p <- missing_profile(m)
stopifnot(identical(names(p), c("n_respondents", "n_items", "item_rate", "person_rate",
  "n_complete", "worst_item")))
stopifnot(p$n_respondents == 3, p$n_items == 3, p$worst_item == "c", p$n_complete == 0)
stopifnot(identical(p$person_rate, c(1, 2, 2) / 3))
p2 <- missing_profile(data.frame(a = 1:2))
stopifnot(is.na(p2$worst_item), p2$n_complete == 2)
stopifnot(inherits(try(missing_profile(m, "z"), silent = TRUE), "try-error"))

s <- data.frame(a = c(1, NA, NA, 1), b = c(1, 1, NA, NA), c = c(1, NA, NA, 1),
  d = c(1, 1, NA, 1))
it <- c("a", "b", "c", "d")
