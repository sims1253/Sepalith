raw <- c(10, 20, 30)
stopifnot(identical(c(convert_norm(raw, 20, 10, "z")), c(-1, 0, 1)))
stopifnot(identical(c(convert_norm(raw, 20, 10, "t")), c(40, 50, 60)))
stopifnot(identical(c(convert_norm(raw, 20, 10, "iq")), c(85, 100, 115)))
stopifnot(identical(c(convert_norm(c(-100, 20, 100), 20, 10, "stanine")), c(1, 5, 9)))
stopifnot(identical(c(convert_norm(c(-100, 100), 20, 10, "sten")), c(1, 10)))
pc <- convert_norm(raw, 20, 10, "percentile")
stopifnot(pc[2] == 50, pc[3] == 84.1, attr(pc, "type") == "percentile")
stopifnot(inherits(try(convert_norm(raw, 20, 0), silent = TRUE), "try-error"))

stopifnot(all.equal(rescale_standard(60, "t", "iq"), 115))
stopifnot(all.equal(rescale_standard(13, "scaled", "z"), 1))
stopifnot(all.equal(rescale_standard(1, "z", "scaled"), 13))
stopifnot(all.equal(rescale_standard(85, "iq", "t"), 40))
stopifnot(all.equal(rescale_standard(50, "percentile", "t"), 50))
stopifnot(all.equal(rescale_standard(0, "z", "percentile"), 50))
stopifnot(inherits(try(rescale_standard(100, "percentile"), silent = TRUE), "try-error"))

nb <- norm_by_group(c(25, 28, 32, 9), c("young", "middle", "older", "young"))
stopifnot(identical(nb$z, c(1, 1, 1, -2.2)), identical(nb$t[1:3], c(60, 60, 60)))
w <- tryCatch(norm_by_group(1, "other"), warning = function(w) conditionMessage(w))
stopifnot(grepl("other", w))
stopifnot(inherits(try(norm_by_group(1, "young", young = c(mean = 1)), silent = TRUE),
  "try-error"))
stopifnot(inherits(try(norm_by_group(1, "middle", middle = c(mean = 1, sd = 0)), silent = TRUE),
  "try-error"))
stopifnot(inherits(try(norm_by_group(1, "older", older = c(m = 1, sd = 1)), silent = TRUE),
  "try-error"))
stopifnot(inherits(try(norm_by_group(1:2, "older"), silent = TRUE), "try-error"))

ref <- c(1, 2, 2, 3)
stopifnot(identical(percentile_rank(c(2, NA), ref), c(25, NA)))
stopifnot(identical(percentile_rank(2, ref, "at_or_below"), 75))
stopifnot(identical(percentile_rank(2, ref, "midpoint"), 50))
stopifnot(all.equal(percentile_rank(2, ref, "normal"), 50))
stopifnot(inherits(try(percentile_rank(1, 5), silent = TRUE), "try-error"))

ds <- describe_norm_score(1)
stopifnot(identical(names(ds), c("z", "t", "iq", "percentile", "stanine", "sten", "band")))
stopifnot(ds$t == 60, ds$iq == 115, ds$stanine == 7, ds$sten == 8, ds$band == "average")
stopifnot(describe_norm_score(-2.5)$band == "very low", describe_norm_score(-1.5)$band == "low")
stopifnot(describe_norm_score(1.5)$band == "high", describe_norm_score(3)$band == "very high")
stopifnot(inherits(try(describe_norm_score(NA_real_), silent = TRUE), "try-error"))

cb <- confidence_band(110, 0.75, 20, mean = 100)
stopifnot(cb$se == 10, cb$centre == 110, all.equal(cb$upper - cb$lower, 2 * qnorm(0.975) * 10))
ct <- confidence_band(110, 0.75, 20, mean = 100, type = "true")
stopifnot(all.equal(ct$se, 20 * sqrt(0.1875)), ct$centre == 107.5)
cd <- confidence_band(110, 0.75, 20, type = "difference")
stopifnot(all.equal(cd$se, 20 * sqrt(0.5)))
stopifnot(inherits(try(confidence_band(1, 1, 1), silent = TRUE), "try-error"))
