set.seed(7)
trait = rnorm(150)
X = sapply(c(-1, 0, 0.5, 1), function(b) as.numeric(trait + rnorm(150, sd = 0.7) > b))
colnames(X) = c("q1", "q2", "q3", "q4")

d = itemStatistic(X, "difficulty")
stopifnot(identical(names(d), colnames(X)), all.equal(unname(d), unname(colMeans(X))))
stopifnot(d[["q1"]] > d[["q4"]])
stopifnot(all.equal(itemStatistic(X * 4, "difficulty", maxScore = 4), d))
stopifnot(all.equal(unname(itemStatistic(X, "variance")), unname(apply(X, 2, var))))
it = itemStatistic(X, "itemTotal")
ir = itemStatistic(X, "itemRest")
stopifnot(all(it > ir), all(ir > 0))
ad = itemStatistic(X, "alphaIfDeleted")
C = cov(X[, -1])
stopifnot(all.equal(ad[["q1"]], 1.5 * (1 - sum(diag(C)) / sum(C))))
dis = itemStatistic(X, "discrimination")
stopifnot(all(dis > 0), all(dis <= 1))

ia = itemAnalysis(X)
stopifnot(identical(names(ia), c("item", "mean", "sd", "difficulty", "itemRest",
  "alphaIfDeleted")))
stopifnot(identical(ia$item, colnames(X)), all.equal(ia$itemRest, unname(ir)))
stopifnot(all.equal(ia$sd, unname(apply(X, 2, sd))), all.equal(ia$alphaIfDeleted, unname(ad)))
stopifnot(identical(itemAnalysis(unname(X))$item, paste0("item", 1:4)))
stopifnot(inherits(try(itemAnalysis(X[, 1:2]), silent = TRUE), "try-error"))

st = data.frame(item = c("a", "b", "c", "d"), difficulty = c(0.1, 0.5, 0.9, 0.5),
  itemRest = c(0.4, 0.1, 0.4, 0.5), alphaIfDeleted = c(0.7, 0.7, 0.7, 0.9))
fl = flagItems(st, alpha = 0.8)
stopifnot(identical(fl$tooHard, c(TRUE, FALSE, FALSE, FALSE)))
stopifnot(identical(fl$tooEasy, c(FALSE, FALSE, TRUE, FALSE)))
stopifnot(identical(fl$weak, c(FALSE, TRUE, FALSE, FALSE)))
stopifnot(identical(fl$hurtsAlpha, c(FALSE, FALSE, FALSE, TRUE)), all(fl$flagged))
stopifnot(!any(flagItems(st)$hurtsAlpha))
stopifnot(inherits(try(flagItems(st[1:2]), silent = TRUE), "try-error"))

resp = c("A", "B", "A", "C", NA, "A")
tot = c(10, 4, 9, 3, 5, 8)
da = distractorAnalysis(resp, "A", tot)
stopifnot(identical(da$n, c(3L, 1L, 1L, 0L)), identical(da$isKey, c(TRUE, FALSE, FALSE, FALSE)))
stopifnot(da$meanTotal[1] == 9, is.na(da$meanTotal[4]), is.na(da$pointBiserial[4]))
stopifnot(da$pointBiserial[1] > 0, da$pointBiserial[2] < 0, all.equal(da$share[1], 0.5))
stopifnot(inherits(try(distractorAnalysis(resp, "E", tot), silent = TRUE), "try-error"))
stopifnot(inherits(try(distractorAnalysis(resp, "A", 1:2), silent = TRUE), "try-error"))

ul = upperLowerIndex(X)
stopifnot(identical(ul$item, colnames(X)), all(ul$upperN == 40), all(ul$lowerN == 40))
stopifnot(all(ul$index > 0), all.equal(ul$index, ul$upperMean - ul$lowerMean))
small = upperLowerIndex(matrix(c(1, 0, 1, 0, 0, 1), 3, dimnames = list(NULL, c("x", "y"))), 0.4)
stopifnot(small$upperN[1] == 1, identical(small$index, c(1, 1)))
stopifnot(inherits(try(upperLowerIndex(X, 0.6), silent = TRUE), "try-error"))
