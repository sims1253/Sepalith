set.seed(42)
trait = rnorm(200)
X = sapply(1:6, function(j) trait + rnorm(200, sd = 0.8))
colnames(X) = paste0("i", 1:6)
C = cov(X)
alphaRef = 6 / 5 * (1 - sum(diag(C)) / sum(C))
stopifnot(all.equal(c(reliabilityCoef(X)), alphaRef))
stopifnot(attr(reliabilityCoef(X, "standardized"), "method") == "standardized")
stopifnot(abs(reliabilityCoef(X, "standardized") - alphaRef) < 0.02)
sh = reliabilityCoef(X, "splitHalf")
stopifnot(sh > 0.8, sh < 1)
stopifnot(reliabilityCoef(X, "lambda2") >= alphaRef)
B = (X > 0) * 1
stopifnot(abs(reliabilityCoef(B, "kr20") - reliabilityCoef(B, "alpha")) < 0.02)
stopifnot(inherits(try(reliabilityCoef(X, "kr20"), silent = TRUE), "try-error"))
stopifnot(inherits(try(reliabilityCoef(X[, 1, drop = FALSE]), silent = TRUE), "try-error"))

fe = alphaInterval(X)
stopifnot(identical(names(fe), c("alpha", "lower", "upper")), fe[["lower"]] < fe[["alpha"]])
stopifnot(fe[["upper"]] > fe[["alpha"]], fe[["upper"]] < 1)
fi = alphaInterval(X, method = "fisher")
stopifnot(fi[["lower"]] < fi[["alpha"]], fi[["upper"]] > fi[["alpha"]])
set.seed(1)
bo = alphaInterval(X, method = "bootstrap", nBoot = 100)
stopifnot(bo[["lower"]] < bo[["alpha"]], bo[["upper"]] > bo[["alpha"]])

stopifnot(all.equal(correctAttenuation(0.4, 0.64, 0.25), 1))
stopifnot(all.equal(correctAttenuation(0.4, 0.64, correct = "x"), 0.5))
stopifnot(all.equal(correctAttenuation(0.4, ryy = 0.25, correct = "y"), 0.8))
stopifnot(correctAttenuation(0.4, 0.5, 0.5, correct = "none") == 0.4)
w = tryCatch(correctAttenuation(0.9, 0.5, 0.5), warning = function(w) "warned")
stopifnot(identical(w, "warned"))
stopifnot(suppressWarnings(correctAttenuation(0.9, 0.5, 0.5)) == 1)
stopifnot(inherits(try(correctAttenuation(0.3, 0), silent = TRUE), "try-error"))

tr = testRetest(c(1, 2, 3, 4, 5, NA), c(2, 3, 4, 5, 6, 1))
stopifnot(identical(names(tr), c("n", "pearson", "spearman", "icc", "meanDiff", "sdDiff",
  "limits")))
stopifnot(tr$n == 5, all.equal(tr$pearson, 1), all.equal(tr$spearman, 1), tr$meanDiff == 1)
stopifnot(tr$sdDiff == 0, tr$icc < 1, tr$icc > 0.5)
stopifnot(identical(names(tr$limits), c("lower", "upper")))
stopifnot(all.equal(testRetest(1:5, 1:5)$icc, 1))
stopifnot(inherits(try(testRetest(1:3, 1:2), silent = TRUE), "try-error"))
stopifnot(inherits(try(testRetest(c(1, 2), c(1, 2)), silent = TRUE), "try-error"))

rt = reliabilityTable(X, list(a = c("i1", "i2", "i3"), b = c("i4", "i5", "i6"), c = "i1"))
stopifnot(identical(rt$scale, c("a", "b", "c")), identical(rt$nItems, c(3, 3, 1)))
stopifnot(all.equal(rt$alpha[1], c(reliabilityCoef(X[, 1:3]))), is.na(rt$alpha[3]))
stopifnot(all.equal(rt$sem[2], rt$sd[2] * sqrt(1 - rt$alpha[2])))
stopifnot(inherits(try(reliabilityTable(X, list(c("i1", "i2"))), silent = TRUE), "try-error"))
stopifnot(inherits(try(reliabilityTable(X, list(a = "zz")), silent = TRUE), "try-error"))

oe = splitHalves(X)
stopifnot(identical(oe$a, c(1, 3, 5)), identical(oe$b, c(2L, 4L, 6L)))
stopifnot(all.equal(oe$spearmanBrown, c(reliabilityCoef(X, "splitHalf"))))
fs = splitHalves(X, "firstSecond")
stopifnot(identical(fs$a, 1:3), identical(fs$b, 4:6))
ba = splitHalves(X, "balanced")
stopifnot(length(ba$a) == 3, length(intersect(ba$a, ba$b)) == 0)
set.seed(3)
ra = splitHalves(X, "random")
stopifnot(length(ra$a) == 3, setequal(c(ra$a, ra$b), 1:6))
stopifnot(inherits(try(splitHalves(X[, 1, drop = FALSE]), silent = TRUE), "try-error"))
