near <- function(a, b, tol = 1e-9) isTRUE(all.equal(a, b, tolerance = tol))
units <- c("deg", "rad", "grad", "arcmin", "arcsec", "turn", "mil", "hour")
full <- c(deg = 360, rad = 2 * pi, grad = 400, arcmin = 21600, arcsec = 1296000, turn = 1,
  mil = 6400, hour = 24)
for (u in units) {
  stopifnot(near(angle.convert(full[[u]], u, "deg"), 360))
  stopifnot(near(angle.convert(360, "deg", u), full[[u]]))
}
stopifnot(near(angle.convert(pi / 2, "rad", "grad"), 100))
stopifnot(inherits(try(angle.convert("1"), silent = TRUE), "try-error"))

stopifnot(identical(angle.normalize(c(-90, 370), "0_360"), c(270, 10)))
stopifnot(identical(angle.normalize(c(190, -190, 180), "pm180"), c(-170, 170, -180)))
stopifnot(near(angle.normalize(-pi / 2, "0_2pi"), 3 * pi / 2))
stopifnot(near(angle.normalize(3 * pi / 2, "pm_pi"), -pi / 2))

w <- ellipsoid.params("wgs84")
stopifnot(identical(names(w), c("name", "a", "f", "b", "e2", "ep2")))
stopifnot(abs(w$b - 6356752.314245) < 1e-5, near(w$e2, 0.00669437999014, 1e-10))
stopifnot(abs(ellipsoid.params("grs80")$b - 6356752.314140) < 1e-5)
stopifnot(ellipsoid.params("clarke1866")$a == 6378206.4)
stopifnot(near(ellipsoid.params("intl1924")$f, 1 / 297))
sp <- ellipsoid.params("sphere")
stopifnot(sp$f == 0, sp$b == sp$a, sp$e2 == 0, sp$ep2 == 0)

e0 <- geodetic.to.ecef(0, 0)
stopifnot(e0$x == 6378137, abs(e0$y) < 1e-9, abs(e0$z) < 1e-9)
ep <- geodetic.to.ecef(0, 90, h = 10)
stopifnot(near(ep$z, w$b + 10))
stopifnot(near(geodetic.to.ecef(90, 0, ellipsoid = "sphere")$y, sp$a))

pts <- geodetic.to.ecef(c(13.4, -120, 0), c(52.5, -33.9, 90), c(100, 2500, 0))
back <- ecef.to.geodetic(pts$x, pts$y, pts$z)
stopifnot(near(back$lon[1:2], c(13.4, -120), 1e-10), near(back$lat, c(52.5, -33.9, 90), 1e-10))
stopifnot(all(abs(back$h - c(100, 2500, 0)) < 1e-4))
bs <- ecef.to.geodetic(0, sp$a + 5, 0, ellipsoid = "sphere")
stopifnot(near(bs$lon, 90), near(bs$h, 5))

p <- angle.parts(-10.5125, "dms")
stopifnot(p$sign == -1, p$whole == 10, p$minutes == 30, near(p$seconds, 45, 1e-6))
q <- angle.parts(2.25, "dm")
stopifnot(q$whole == 2, q$minutes == 15, q$seconds == 0)
h <- angle.parts(25.5, "hms")
stopifnot(h$whole == 1, h$minutes == 30, near(h$seconds, 0))
air <- ellipsoid.params("airy1830")
stopifnot(air$a == 6377563.396, abs(air$b - 6356256.909) < 1e-3)
stopifnot(identical(angle.normalize(c(-100, 450), "0_400"), c(300, 50)))
stopifnot(identical(angle.normalize(c(250, -250), "pm200"), c(-150, 150)))
hm <- angle.parts(-1.75, "hm")
stopifnot(hm$sign == -1, hm$whole == 1, hm$minutes == 45, hm$seconds == 0)
