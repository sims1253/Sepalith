stopifnot(identical(geo$xmax, c(1, 3)), identical(geo$ymin, c(0, 1)))
stopifnot(inherits(try(cellGeometry(7, g), silent = TRUE), "try-error"))

lon = c(0.5, 0.6, 2.5, 9)
lat = c(0.5, 0.4, 1.5, 9)
val = c(1, 3, 10, 100)
cnt = aggregateToGrid(lon, lat, val, g, "count")
stopifnot(identical(dim(cnt), c(2L, 3L)), cnt[1, 1] == 2, cnt[2, 3] == 1, sum(cnt) == 3)
stopifnot(aggregateToGrid(lon, lat, val, g, "sum")[1, 1] == 4)
mn = aggregateToGrid(lon, lat, val, g, "mean")
stopifnot(mn[1, 1] == 2, is.na(mn[1, 2]))
stopifnot(aggregateToGrid(lon, lat, val, g, "min")[1, 1] == 1)
stopifnot(aggregateToGrid(lon, lat, val, g, "median")[1, 1] == 2)
sdg = aggregateToGrid(lon, lat, val, g, "sd")
stopifnot(isTRUE(all.equal(sdg[1, 1], sd(c(1, 3)))), is.na(sdg[2, 3]))
stopifnot(aggregateToGrid(lon, lat, val, g, "max")[2, 3] == 10)

