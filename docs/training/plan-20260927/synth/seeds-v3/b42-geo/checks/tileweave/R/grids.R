g = makeGrid(0, 0, 3, 2, 1)
stopifnot(inherits(g, "tw_grid"), g$nx == 3L, g$ny == 2L, identical(g$xEdges, c(0, 1, 2, 3)))
stopifnot(identical(g$yEdges, c(0, 1, 2)))
stopifnot(makeGrid(0, 0, 2.5, 1, 1)$nx == 3L)
stopifnot(inherits(try(makeGrid(1, 0, 0, 1, 1), silent = TRUE), "try-error"))
stopifnot(inherits(try(makeGrid(0, 1, 1, 0, 1), silent = TRUE), "try-error"))
stopifnot(inherits(try(makeGrid(0, 0, 1, 1, -1), silent = TRUE), "try-error"))

ci = cellIndex(c(0.5, 2.5, 5, 1.5), c(0.5, 1.5, 0.5, -1), g)
