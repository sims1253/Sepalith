near <- function(a, b, tol = 1e-6) isTRUE(all.equal(a, b, tolerance = tol))
projs <- c("equirectangular", "mercator", "web_mercator", "sinusoidal", "lambert_cea", "miller")
lon <- c(-120, 0, 45.5)
lat <- c(-60, 0, 33.3)
for (p in projs) {
  fw <- project_forward(lon, lat, p)
  stopifnot(identical(names(fw), c("x", "y")), near(fw$y[2], 0))
  bk <- project_inverse(fw$x, fw$y, p)
  stopifnot(near(bk$lon, lon), near(bk$lat, lat))
}
stopifnot(near(project_forward(90, 0, "equirectangular", radius = 1)$x, pi / 2))
stopifnot(near(project_forward(0, 90, "lambert_cea", radius = 1)$y, 1))
stopifnot(near(project_forward(90, 60, "sinusoidal", radius = 1)$x, pi / 4))
stopifnot(inherits(try(project_forward(0, 90, "mercator"), silent = TRUE), "try-error"))
wm <- project_forward(0, 89, "web_mercator", radius = 1)
stopifnot(near(wm$y, pi))
stopifnot(project_inverse(0, 0, "sinusoidal")$lat == 0)

e <- projection_extent("web_mercator", radius = 1)
stopifnot(near(unname(e["ymax"]), pi), near(unname(e["xmin"]), -pi))
stopifnot(near(unname(projection_extent("lambert_cea", radius = 2)["ymax"]), 2))
stopifnot(near(unname(projection_extent("equirectangular", radius = 1)["ymax"]), pi / 2))
stopifnot(near(unname(projection_extent("sinusoidal", radius = 1)["ymin"]), -pi / 2))
me <- projection_extent("mercator", radius = 1, max_lat = 60)
stopifnot(near(unname(me["ymax"]), project_forward(0, 60, "mercator", radius = 1)$y))
mi <- projection_extent("miller", radius = 1)
stopifnot(near(unname(mi["ymax"]), project_forward(0, 90, "miller", radius = 1)$y))

d0 <- projection_distortion(0, "mercator")
stopifnot(d0$h == 1, d0$k == 1, d0$angle == 0)
d60 <- projection_distortion(60, "mercator")
stopifnot(near(d60$area, 4), near(d60$angle, 0))
stopifnot(near(projection_distortion(60, "lambert_cea")$area, 1))
stopifnot(near(projection_distortion(60, "equirectangular")$k, 2))
stopifnot(projection_distortion(30, "miller")$angle > 0)
stopifnot(inherits(try(projection_distortion(90, "miller"), silent = TRUE), "try-error"))

df <- data.frame(id = 1:2, x = c(10, -20), y = c(40, -5))
r1 <- reproject_df(df, "lonlat", "mercator")
stopifnot(attr(r1, "projection") == "mercator", r1$id[2] == 2)
r2 <- reproject_df(r1, "mercator", "lonlat")
stopifnot(near(r2$x, df$x), near(r2$y, df$y))
r3 <- reproject_df(r1, "merc", "sinusoidal")
stopifnot(near(project_inverse(r3$x, r3$y, "sinusoidal")$lat, df$y))
stopifnot(inherits(try(reproject_df(df, "lonlat", "miller", c("a", "b")), silent = TRUE),
  "try-error"))
stopifnot(identical(projection_distortion(c(0, 45), "web_mercator"),
  projection_distortion(c(0, 45), "mercator")))
