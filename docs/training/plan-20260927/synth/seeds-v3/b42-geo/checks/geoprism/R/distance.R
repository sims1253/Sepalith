stopifnot(near(geo_bearing(0, 0, 10, 0, "reverse"), 270))
stopifnot(near(geo_bearing(0, 0, -10, 0, "rhumb"), 270))
stopifnot(near(geo_bearing(170, 0, -170, 0, "rhumb"), 90))
