utc <- function(s) as.POSIXct(s, tz = "UTC")
x <- utc("2024-03-31 14:37:45")

stopifnot(time.floor(x, "minute") == utc("2024-03-31 14:37:00"))
stopifnot(time.floor(x, "hour") == utc("2024-03-31 14:00:00"))
stopifnot(time.floor(x, "day") == utc("2024-03-31"))
stopifnot(time.floor(x, "month") == utc("2024-03-01"))
stopifnot(time.floor(utc("2024-03-31 14:37:45.8"), "second") == x)
stopifnot(time.floor(x, "week") == utc("2024-03-25"))
stopifnot(format(time.floor(utc("2024-03-31 16:00"), "day", tz = "Asia/Tokyo"),
  tz = "Asia/Tokyo") == "2024-04-01")

stopifnot(time.ceiling(x, "minute") == utc("2024-03-31 14:38:00"))
stopifnot(time.ceiling(x, "hour") == utc("2024-03-31 15:00:00"))
stopifnot(time.ceiling(x, "day") == utc("2024-04-01"))
stopifnot(time.ceiling(x, "month") == utc("2024-04-01"))
stopifnot(time.ceiling(utc("2024-03-31 14:37:45.2"), "second") == utc("2024-03-31 14:37:46"))
stopifnot(time.ceiling(x, "week") == utc("2024-04-01"))
stopifnot(time.ceiling(utc("2024-03-01"), "month") == utc("2024-03-01"))

stopifnot(time.round(x, "minute") == utc("2024-03-31 14:38:00"))
stopifnot(time.round(x, "hour") == utc("2024-03-31 15:00:00"))
stopifnot(time.round(utc("2024-03-31 11:59:59"), "day") == utc("2024-03-31"))
stopifnot(time.round(utc("2024-03-16 12:00:00"), "month") == utc("2024-04-01"))
stopifnot(time.round(utc("2024-03-16 11:00:00"), "month") == utc("2024-03-01"))
stopifnot(time.round(x, "week") == utc("2024-04-01"))

stopifnot(parse.timestamp("2024-03-05 14:30:00") == utc("2024-03-05 14:30:00"))
stopifnot(is.na(parse.timestamp("2024/03/05 14:30")))
stopifnot(parse.timestamp("2024-03-05 14:30:00.250", "iso.ms") ==
  utc("2024-03-05 14:30:00") + 0.25)
stopifnot(parse.timestamp("2024-03-05T14:30:00Z", "iso.t") == utc("2024-03-05 14:30:00"))
st <- parse.timestamp("2024-03-05T14:30:00Z", "iso.t", tz = "Europe/Berlin")
stopifnot(as.numeric(st) == as.numeric(utc("2024-03-05 14:30:00")))
stopifnot(attr(st, "tzone") == "Europe/Berlin")
stopifnot(parse.timestamp(1709649000, "epoch") == utc("2024-03-05 14:30:00"))
stopifnot(parse.timestamp("1709649000500", "epoch.ms") == utc("2024-03-05 14:30:00.5"))
h <- parse.timestamp(c("Tue, 05 Mar 2024 14:30:00 GMT", "bogus"), "http")
stopifnot(h[1] == utc("2024-03-05 14:30:00"), is.na(h[2]))

ct <- time.convert(x, "America/New_York")
stopifnot(as.numeric(ct) == as.numeric(x), format(ct) == "2024-03-31 10:37:45")
stopifnot(inherits(try(time.convert(Sys.Date(), "UTC"), silent = TRUE), "try-error"))

ts <- utc(c("2024-03-05 10:05:00", "2024-03-05 10:55:00", "2024-03-05 12:01:00", NA))
b <- time.bucket(ts, "hour")
stopifnot(identical(names(b), c("bucket", "label", "n")), identical(b$n, c(2L, 1L)))
stopifnot(b$label[1] == "2024-03-05 10:00")
bf <- time.bucket(ts, "hour", fill = TRUE)
stopifnot(identical(bf$n, c(2L, 0L, 1L)), bf$label[2] == "2024-03-05 11:00")
stopifnot(time.bucket(ts, "day")$n == 3L, time.bucket(ts, "month")$label == "2024-03")
stopifnot(nrow(time.bucket(ts, "minute")) == 3L)
stopifnot(time.bucket(ts, "week")$label == "2024-W10")
stopifnot(identical(time.bucket(ts[1:2] + c(0, 1), "second", fill = FALSE)$n, c(1L, 1L)))
stopifnot(nrow(time.bucket(utc(c("2024-03-05 10:00:00", "2024-03-05 10:00:03")), "second",
  fill = TRUE)) == 4L)
stopifnot(time.round(utc("2024-03-31 14:37:45.6"), "second") == utc("2024-03-31 14:37:46"))
