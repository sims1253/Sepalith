A <- matrix(c(4, -1, 0, -1, 4, -1, 0, -1, 4), 3, 3)
b <- c(1, 2, 3)
dd <- diag.dominance(A)
stopifnot(dd$rows$strict, dd$cols$strict, all(dd$rows$margin == c(3, 2, 3)))
N <- matrix(c(1, 3, 0, 2, 5, 0, 0, 1, 1), 3, 3)
dd <- diag.dominance(N)
stopifnot(!dd$rows$strict, !dd$cols$weak)
stopifnot(identical(names(dd$cols), c("margin", "ratio", "strict", "weak", "worst")))
stopifnot(dd$rows$worst == 1L, dd$cols$worst == 1L, dd$rows$ratio[1] == 2, dd$cols$ratio[2] == 0.4)
stopifnot(dd$rows$margin[1] == -1, dd$cols$margin[1] == -2)
stopifnot(inherits(try(diag.dominance(matrix(1, 2, 3)), silent = TRUE), "try-error"))
stopifnot(inherits(try(diag.dominance(matrix(c(0, 1, 1, 2), 2)), silent = TRUE), "try-error"))

sp <- iter.split(A, "jacobi")
stopifnot(all(sp$M == diag(4, 3)), abs(sp$radius - sqrt(2) / 4) < 1e-12)
sp.gs <- iter.split(A, "gauss.seidel")
stopifnot(sp.gs$M[2, 1] == -1, sp.gs$M[1, 2] == 0, abs(sp.gs$radius - 1 / 8) < 1e-12)
stopifnot(all(iter.split(A, "sor", omega = 1)$M == sp.gs$M))
stopifnot(all(iter.split(A, "richardson", omega = 0.25)$M == diag(4, 3)))
stopifnot(inherits(try(iter.split(diag(c(1, 0)), "jacobi"), silent = TRUE), "try-error"))

exact <- solve(A, b)
for (m in c("jacobi", "gauss.seidel", "sor", "richardson")) {
  fit <- iter.solve(A, b, m, omega = if (m == "richardson") 0.2 else 1.1)
  stopifnot(fit$reason == "converged", max(abs(fit$x - exact)) < 1e-9, all(fit$checks[1:2]))
}
stopifnot(iter.solve(A, b, "gauss.seidel")$iter < iter.solve(A, b, "jacobi")$iter)
stopifnot(iter.solve(A, b, max.iter = 3L)$reason == "max.iter")
div <- iter.solve(diag(c(100, 1)), c(1, 1), "richardson")
stopifnot(div$reason == "diverged", div$checks[["diverged"]], div$radius == 99)

cg <- cg.solve(A, b)
stopifnot(cg$reason == "converged", cg$iter <= 5L, max(abs(cg$x - exact)) < 1e-9)
stopifnot(cg.solve(crossprod(matrix(1:16, 4)) + diag(4), 1:4, max.iter = 1L)$reason == "max.iter")
stopifnot(inherits(try(cg.solve(N, b), silent = TRUE), "try-error"))

w <- sor.omega(A)
stopifnot(w > 1, w < 2, abs(w - 2 / (1 + sqrt(1 - 1 / 8))) < 1e-12)
stopifnot(inherits(try(sor.omega(matrix(c(1, 2, 2, 1), 2)), silent = TRUE), "try-error"))
