A <- matrix(c(4, 1, 0, 1, 3, 1, 0, 1, 1), 3, 3)
ev <- eigen(A, symmetric = TRUE)
stopifnot(rayleigh.quotient(A, c(1, 0, 0)) == 4, rayleigh.quotient(diag(2), c(3, 4)) == 1)

g <- gershgorin(A)
stopifnot(identical(names(g$rows), c("center", "radius", "lower", "upper", "isolated")))
stopifnot(all(g$rows$radius == c(1, 2, 1)), all(ev$values >= g$bounds[["lower"]]))
stopifnot(all(ev$values <= g$bounds[["upper"]]), !any(g$rows$isolated))
N <- matrix(c(5, 2, 0, 1), 2, 2)
gn <- gershgorin(N)
stopifnot(all(gn$rows$radius == c(0, 2)), all(gn$cols$radius == c(2, 0)))
stopifnot(identical(gn$rows$isolated, c(TRUE, TRUE)), identical(gn$cols$isolated, c(TRUE, TRUE)))
stopifnot(identical(gn$bounds, c(lower = 1, upper = 5)))
stopifnot(inherits(try(gershgorin(matrix(1, 2, 3)), silent = TRUE), "try-error"))

pm <- power.method(A)
stopifnot(pm$converged, abs(pm$value - ev$values[1]) < 1e-8, all(pm$checks))
pm <- power.method(A, "inverse")
stopifnot(pm$converged, abs(pm$value - ev$values[3]) < 1e-8)
pm <- power.method(A, "shifted", shift = 3.2)
near <- ev$values[which.min(abs(ev$values - 3.2))]
stopifnot(pm$converged, abs(pm$value - near) < 1e-8)
pm <- power.method(A, "rayleigh", x0 = c(0, 1, 0))
stopifnot(pm$converged, min(abs(ev$values - pm$value)) < 1e-8, pm$iter < 20L)
stopifnot(!power.method(A, max.iter = 2L)$converged)
neg <- power.method(diag(c(-5, 1)), x0 = c(1, 1))
stopifnot(neg$converged, abs(neg$value + 5) < 1e-8)

for (m in c("hotelling", "wielandt", "projection")) {
  D <- deflate(A, ev$values[1], ev$vectors[, 1] * 3, method = m)
  dv <- sort(Re(eigen(D, only.values = TRUE)$values))
  stopifnot(all(abs(dv - sort(c(0, ev$values[2:3]))) < 1e-10))
}
W <- deflate(N, 5, c(2, 1), method = "wielandt")
stopifnot(all(abs(W %*% c(2, 1)) < 1e-12), all(W[1, ] == 0), abs(W[2, 2] - 1) < 1e-12)
stopifnot(inherits(try(deflate(A, 1, 1:2), silent = TRUE), "try-error"))

te <- top.eigen(A, k = 2L)
stopifnot(all(abs(te$values - ev$values[1:2]) < 1e-7), ncol(te$vectors) == 2L, all(te$converged))
stopifnot(abs(abs(sum(te$vectors[, 1] * ev$vectors[, 1])) - 1) < 1e-6)
stopifnot(all(abs(top.eigen(A, 2L, method = "projection")$values - ev$values[1:2]) < 1e-7))
stopifnot(inherits(try(top.eigen(N), silent = TRUE), "try-error"))
stopifnot(inherits(try(top.eigen(A, k = 4), silent = TRUE), "try-error"))

er <- eigen.residuals(A, ev$values, ev$vectors)
stopifnot(identical(names(er), c("value", "residual", "norm", "orthogonality")))
stopifnot(all(er$residual < 1e-10), all(abs(er$norm - 1) < 1e-12), all(er$orthogonality < 1e-10))
er1 <- eigen.residuals(A, 1, matrix(c(1, 0, 0)))
stopifnot(er1$orthogonality == 0, er1$residual > 1)
stopifnot(inherits(try(eigen.residuals(A, 1:2, ev$vectors), silent = TRUE), "try-error"))
stopifnot(inherits(try(eigen.residuals(A, 1, c(1, 0)), silent = TRUE), "try-error"))
