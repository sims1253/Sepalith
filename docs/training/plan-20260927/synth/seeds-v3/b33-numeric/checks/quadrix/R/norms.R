x <- c(3, -4, 0)
stopifnot(vec_norm(x) == 5, vec_norm(x, "l1") == 7, vec_norm(x, "linf") == 4)
stopifnot(abs(vec_norm(x, "lp", p = 2) - 5) < 1e-12)
stopifnot(inherits(try(vec_norm("a"), silent = TRUE), "try-error"))
stopifnot(inherits(try(vec_norm(x, "lp", p = 0.5), silent = TRUE), "try-error"))

A <- matrix(c(1, -2, 3, 4), 2, 2)
stopifnot(mat_norm(A) == 7, mat_norm(A, "inf") == 6, mat_norm(A, "max") == 4)
stopifnot(abs(mat_norm(A, "frobenius") - sqrt(30)) < 1e-12)
sv <- svd(A)$d
stopifnot(abs(mat_norm(A, "spectral") - sv[1]) < 1e-12)
stopifnot(abs(mat_norm(A, "nuclear") - sum(sv)) < 1e-12)
stopifnot(inherits(try(mat_norm(1:3), silent = TRUE), "try-error"))
stopifnot(inherits(try(mat_norm(matrix(c(1, NA), 1)), silent = TRUE), "try-error"))

stopifnot(cond_number(diag(c(1, 4))) == 4, cond_number(diag(c(1, 4)), "spectral") == 4)
stopifnot(abs(cond_number(A, "inf") - mat_norm(A, "inf") * mat_norm(solve(A), "inf")) < 1e-12)
stopifnot(cond_number(matrix(1, 2, 2)) == Inf, cond_number(matrix(0, 2, 2), "spectral") == Inf)
stopifnot(inherits(try(cond_number(matrix(1, 2, 3)), silent = TRUE), "try-error"))

rep <- norm_report(A)
stopifnot(identical(rep$norm, c("one", "inf", "max", "frobenius", "spectral", "nuclear")))
stopifnot(abs(rep$value[6] - sum(sv)) < 1e-12, rep$where[6] == "all singular values")
stopifnot(identical(rep$where[1:3], c("col 2", "row 2", "row 2, col 2")))
stopifnot(rep$value[1] == 7, rep$value[2] == 6, abs(rep$value[5] - sv[1]) < 1e-12)

nb <- norm_bounds(A)
stopifnot(nrow(nb) == 6L, all(nb$holds), nb$bound[1] == "spectral_frobenius")
set.seed(42)
nb <- norm_bounds(matrix(rnorm(12, sd = 3), 3, 4))
stopifnot(all(nb$holds), identical(names(nb), c("bound", "lhs", "rhs", "holds")))

M <- matrix(c(3, 0, 4, 0), 2, 2, dimnames = list(c("a", "b"), c("u", "v")))
res <- suppressWarnings(normalize_margin(M))
stopifnot(all.equal(res$scaled["a", ], c(u = 0.6, v = 0.8)), all(res$scaled["b", ] == 0))
w <- tryCatch(normalize_margin(M), warning = conditionMessage)
stopifnot(identical(w, "1 rows with zero norm left unscaled."))
stopifnot(inherits(try(normalize_margin(1:3), silent = TRUE), "try-error"))
stopifnot(inherits(try(normalize_margin(M, tol = -1), silent = TRUE), "try-error"))
res <- normalize_margin(M, "cols", type = "l1")
stopifnot(all.equal(colSums(abs(res$scaled)), c(u = 1, v = 1)), all(res$norms == c(3, 4)))

X <- rbind(p = c(0, 0), q = c(3, 4), r = c(1, 0))
stopifnot(row_distances(X)["p", "q"] == 5, row_distances(X, "manhattan")["p", "q"] == 7)
stopifnot(row_distances(X, "chebyshev")[2, 1] == 4, isSymmetric(row_distances(X)))
stopifnot(abs(row_distances(X, "minkowski", p = 2)[1, 2] - 5) < 1e-12)
stopifnot(abs(row_distances(X, "cosine")["q", "r"] - 0.4) < 1e-12)
