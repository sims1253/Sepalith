A = matrix(c(1, 2, NA, 4, 5, 9), 2, 3, dimnames = list(c("a", "b"), c("x", "y", "z")))
stopifnot(all.equal(marginStat(A, "mean"), c(3, 5)))
stopifnot(all.equal(marginStat(A, "median", "cols"), c(1.5, 4, 7)))
stopifnot(all.equal(marginStat(A, "sd", "cols")[1], sd(c(1, 2))))
stopifnot(all(marginStat(A, "min") == c(1, 2)))
stopifnot(all(marginStat(A, "max") == c(5, 9)), all(marginStat(A, "range", "cols") == c(1, 0, 4)))
stopifnot(all(marginStat(A, "nNA", "cols") == c(0, 1, 0)), is.na(marginStat(A, naRm = FALSE)[1]))

rs = rowSummary(A)
stopifnot(identical(names(rs), c("index", "name", "mean", "sd", "min", "max", "nNA", "share")))
stopifnot(identical(rs$name, c("a", "b")), all(rs$nNA == c(1, 0)), all(rs$max == c(5, 9)))
stopifnot(all.equal(rs$share, c(6, 15) / 21))
cs = colSummary(A, stats = c("mean", "range"))
stopifnot(nrow(cs) == 3L, identical(cs$name, c("x", "y", "z")), cs$mean[3] == 7)
stopifnot(identical(names(cs), c("index", "name", "mean", "range", "share")))
stopifnot(all(is.na(colSummary(unname(A))$name)))
stopifnot(inherits(try(rowSummary(1:3), silent = TRUE), "try-error"))
stopifnot(inherits(try(colSummary(matrix("a")), silent = TRUE), "try-error"))

fl = structureFlags(diag(c(2, 3)))
stopifnot(all(fl[c("square", "symmetric", "diagonal", "upper", "lower", "tridiagonal", "posDef")]))
stopifnot(!fl[["orthogonal"]], !fl[["skew"]])
rot = matrix(c(0, 1, -1, 0), 2, 2)
fl = structureFlags(rot)
stopifnot(fl[["orthogonal"]], fl[["skew"]], !fl[["symmetric"]], !fl[["upper"]], !fl[["posDef"]])
fl = structureFlags(matrix(c(1, 0, 2, 1), 2, 2))
stopifnot(fl[["upper"]], !fl[["lower"]], !fl[["diagonal"]])
fl = structureFlags(matrix(c(1, 1, 0, 1, 1, 1, 5, 1, 1), 3, 3))
stopifnot(!fl[["tridiagonal"]])
stopifnot(structureFlags(matrix(c(1, 1, 0, 1, 1, 1, 0, 1, 1), 3, 3))[["tridiagonal"]])
stopifnot(!any(structureFlags(matrix(1, 2, 3))), length(structureFlags(matrix(1, 2, 3))) == 9L)

pr = matrixProfile(matrix(c(2, 0, 0, 0, 3, 0, 1, 0, 0), 3, 3))
stopifnot(identical(names(pr), c("dim", "rank", "trace", "det", "sparsity", "range",
                                 "frobenius", "asymmetry", "nNA")))
stopifnot(pr$rank == 2L, pr$trace == 5, pr$det == 0, abs(pr$sparsity - 6 / 9) < 1e-12)
stopifnot(identical(pr$range, c(0, 3)), pr$frobenius == sqrt(14), pr$nNA == 0L)
stopifnot(abs(pr$asymmetry - sqrt(0.5) / sqrt(14)) < 1e-12, matrixProfile(diag(2))$asymmetry == 0)
pna = matrixProfile(matrix(c(1, NA, 3, 4), 2, 2))
stopifnot(pna$nNA == 1L, is.na(pna$rank), length(pna) == 9L)
stopifnot(inherits(try(matrixProfile(A), silent = TRUE), "try-error"))
stopifnot(inherits(try(matrixProfile(1:4), silent = TRUE), "try-error"))

sp = spectrumSummary(diag(c(4, -2, 0)))
stopifnot(sp$radius == 4, sp$minAbs == 0, sp$nPositive == 1L, sp$nNegative == 1L, sp$nZero == 1L)
stopifnot(sp$condition == Inf, sp$inertia == "(1, 1, 1)", sp$trace == 2, sp$det == 0)
sp2 = spectrumSummary(diag(c(4, 2)))
stopifnot(sp2$condition == 2, sp2$det == 8, sp2$inertia == "(2, 0, 0)")
stopifnot(inherits(try(spectrumSummary(rot), silent = TRUE), "try-error"))

sm = summarizeMatrices(list(I = diag(2), R = rot))
stopifnot(identical(names(sm), c("matrix", "rank", "trace", "det", "frobenius", "maxAbs",
                                 "condition")))
stopifnot(identical(sm$matrix, c("I", "R")), all(sm$rank == 2), all(sm$det == 1), sm$trace[2] == 0)
stopifnot(all(sm$condition == 1), all(sm$maxAbs == 1), all(sm$frobenius == sqrt(2)))
stopifnot(summarizeMatrices(list(matrix(1, 2, 2)), "condition")$condition > 1e10)
stopifnot(identical(summarizeMatrices(list(diag(3)), "trace")$matrix, "m1"))
stopifnot(inherits(try(summarizeMatrices(list(diag(2)), "norm"), silent = TRUE), "try-error"))
stopifnot(inherits(try(rowSummary(A, stats = "mode"), silent = TRUE), "try-error"))
stopifnot(inherits(try(colSummary(A, stats = c("mean", "iqr")), silent = TRUE), "try-error"))
