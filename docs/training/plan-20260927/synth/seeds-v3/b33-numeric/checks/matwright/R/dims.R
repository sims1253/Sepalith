A = matrix(c(1, NA, 0, NA, NA, NA, 2, NA, 0), 3, 3)
d = dropEmpty(A)
stopifnot(all(dim(d) == c(2L, 2L)), attr(d, "droppedRows") == 2L, attr(d, "droppedCols") == 2L)
d = dropEmpty(A, zeroIsEmpty = TRUE)
stopifnot(all(dim(d) == c(1L, 2L)), identical(attr(d, "droppedRows"), c(2L, 3L)))
d = dropEmpty(A, rows = FALSE)
stopifnot(nrow(d) == 3L, ncol(d) == 2L, identical(attr(d, "droppedRows"), integer(0)))
stopifnot(all(dim(dropEmpty(A, cols = FALSE)) == c(2L, 3L)))

M = matrix(1:4, 2, 2)
P = padMatrix(M, top = 1, bottom = 2, left = 1, right = 3, value = -1)
stopifnot(all(dim(P) == c(5L, 6L)), P[2, 2] == 1, P[3, 3] == 4, P[1, 1] == -1, P[5, 6] == -1)
stopifnot(identical(padMatrix(M), M))
stopifnot(inherits(try(padMatrix(M, top = -1), silent = TRUE), "try-error"))
stopifnot(inherits(try(padMatrix(M, right = 1.5), silent = TRUE), "try-error"))

N = matrix(1:6, 2, 3, dimnames = list(c("a", "b"), c("x", "y", "z")))
stopifnot(identical(permuteDims(N, c("b", "a"))[, "x"], c(b = 2L, a = 1L)))
stopifnot(identical(colnames(permuteDims(N, colOrder = 3:1)), c("z", "y", "x")))
stopifnot(identical(permuteDims(N), N))
stopifnot(inherits(try(permuteDims(N, c(1, 1)), silent = TRUE), "try-error"))
stopifnot(inherits(try(permuteDims(N, colOrder = c("x", "q", "z")), silent = TRUE), "try-error"))

B = matrix(7:8, 1, 2, dimnames = list("c", c("y", "w")))
al = alignDims(N, B, fill = 0)
stopifnot(identical(dimnames(al$A), list(c("a", "b", "c"), c("x", "y", "z", "w"))))
stopifnot(al$A["a", "w"] == 0, al$B["c", "w"] == 8, al$A["b", "z"] == 6)
stopifnot(identical(al$addedRows, list(A = "c", B = c("a", "b"))))
stopifnot(identical(al$addedCols, list(A = "w", B = c("x", "z"))))
stopifnot(inherits(try(alignDims(M, B), silent = TRUE), "try-error"))
stopifnot(inherits(try(alignDims(unname(N)[, 1, drop = FALSE], B), silent = TRUE), "try-error"))

Q = matrix(1:20, 4, 5)
bl = blockSplit(Q, c(1, 3), c(2, 2, 1))
stopifnot(all(dim(bl) == c(2L, 3L)), identical(bl[[1, 1]], Q[1, 1:2, drop = FALSE]))
stopifnot(identical(bl[[2, 3]], Q[2:4, 5, drop = FALSE]))
stopifnot(identical(blockSplit(Q)[[1, 1]], Q))
stopifnot(inherits(try(blockSplit(Q, c(2, 1)), silent = TRUE), "try-error"))
stopifnot(inherits(try(blockSplit(Q, colSizes = c(5, 0)), silent = TRUE), "try-error"))

R = matrix(c(1, NA, 2, NA), 2, 2, dimnames = list(c("r", "r"), NULL))
info = dimInfo(R)
stopifnot(info$rows$n == 2L, info$rows$named, identical(info$rows$duplicated, "r"))
stopifnot(!info$cols$named, is.null(info$cols$duplicated))
stopifnot(identical(info$rows$allNA, 2L), length(info$cols$allNA) == 0L)
stopifnot(length(info$rows$constant) == 0L, identical(info$cols$constant, 1:2))
info = dimInfo(matrix(c(1, 1, 2, 3), 2, 2))
stopifnot(identical(info$rows$constant, integer(0)), identical(info$cols$constant, 1L))
