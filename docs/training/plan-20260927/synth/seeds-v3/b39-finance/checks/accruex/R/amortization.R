near = function(a, b) isTRUE(all.equal(a, b, tolerance = 1e-8))

stopifnot(near(remainingBalance(1200, 0, 12, 3), 900))
stopifnot(near(remainingBalance(1000, 0.05, 3, 0), 1000))
stopifnot(near(remainingBalance(1000, 0.05, 3, 3), 0))

a = amortizationSchedule(1000, 0.05, 3)
stopifnot(near(a$closing[3], 0), near(a$payment[1], a$payment[3]), a$interest[1] == 50)
stopifnot(near(a$closing[1], remainingBalance(1000, 0.05, 3, 1)))
stopifnot(near(amortizationSchedule(900, 0, 3)$principal, rep(300, 3)))
l = amortizationSchedule(1000, 0.1, 4, "linear")
stopifnot(all(l$principal == 250), l$interest[2] == 75, near(l$closing[4], 0))
b = amortizationSchedule(1000, 0.1, 3, "bullet")
stopifnot(identical(b$principal, c(0, 0, 1000)), all(b$interest == 100))
bl = amortizationSchedule(1000, 0.05, 4, "balloon", balloon = 400)
stopifnot(near(bl$payment[4], bl$payment[1] + 400), near(bl$closing[4], 0))

tot = scheduleTotals(l, periodsPerYear = 2L)
stopifnot(tot$periods == 4L, near(tot$finalBalance, 0))
stopifnot(identical(unname(tot$overall), c(250, 1000, 1250)))
stopifnot(identical(tot$byYear$year, 1:2), identical(tot$byYear$interest, c(175, 75)))
stopifnot(identical(tot$byYear$principal, c(500, 500)), identical(tot$byYear$payment, c(675, 575)))
stopifnot(nrow(scheduleTotals(a)$byYear) == 1L)

price = function(c, y, n) sum(1000 * c / (1 + y)^(1:n)) + 1000 / (1 + y)^n
pr = bondAmortization(price(0.05, 0.035, 4), 1000, 0.05, 0.035, 4)
stopifnot(all(pr$amortized > 0), near(pr$closing[4], 1000))
stopifnot(near(pr$expense[1], price(0.05, 0.035, 4) * 0.035), pr$coupon[1] == 50)
di = bondAmortization(price(0.03, 0.045, 4), 1000, 0.03, 0.045, 4)
stopifnot(all(di$amortized > 0), near(di$closing[4], 1000))
stopifnot(near(di$closing[1], di$opening[1] + di$amortized[1]))

s = amortizationSchedule(100, 0.1, 2, "linear")
csv = renderSchedule(s)
stopifnot(length(csv) == 3L, csv[1] == "period,opening,interest,principal,payment,closing")
stopifnot(csv[2] == "1,100.00,10.00,50.00,60.00,50.00")
tsv = renderSchedule(s, "tsv", digits = 1L)
stopifnot(tsv[3] == "2\t50.0\t5.0\t50.0\t55.0\t0.0")
md = renderSchedule(s, "markdown")
stopifnot(length(md) == 4L, startsWith(md[1], "| period | opening"), grepl("^\\|---:", md[2]))
fx = renderSchedule(s, "fixed")
stopifnot(length(fx) == 3L, length(unique(nchar(fx))) == 1L)
