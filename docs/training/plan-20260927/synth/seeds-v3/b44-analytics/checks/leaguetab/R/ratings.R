fails <- function(expr) inherits(try(expr, silent = TRUE), "try-error")
near <- function(a, b) all(abs(a - b) < 1e-9)
kb <- c(league = 20, cup = 30)

stopifnot(isTRUE(check_rating_args(1500, 60, 400, kb)))
stopifnot(fails(check_rating_args("a", 60, 400, kb)))
stopifnot(fails(check_rating_args(1500, NA, 400, kb)))
stopifnot(fails(check_rating_args(1500, -1, 400, kb)))
stopifnot(fails(check_rating_args(1500, 60, c(1, 2), kb)))
stopifnot(fails(check_rating_args(1500, 60, 0, kb)), fails(check_rating_args(1500, 60, 400, 20)))
stopifnot(fails(check_rating_args(1500, 60, 400, c(a = -1))))

e_home <- 1 / (1 + 10^(-60 / 400))
u <- elo_update(1500, 1500, 2, 0, "league")
stopifnot(near(u$expected, e_home), near(u$delta, 20 * (1 - e_home)), near(u$home + u$away, 3000))
u <- elo_update(1500, 1500, 4, 0, "cup")
stopifnot(near(u$delta, 30 * 3 * (1 - e_home)))
u <- elo_update(1500, 1500, 1, 1, "friendly")
stopifnot(near(u$expected, 1 / (1 + 10^(-30 / 400))), near(u$delta, 10 * (0.5 - u$expected)))
u <- elo_update(1500, 1500, 0, 2, "playoff")
stopifnot(near(u$delta, 40 * 2 * (0 - e_home)))
u <- elo_update(1500, 1500, 3, 1, "tournament")
stopifnot(near(u$expected, 0.5), near(u$delta, 25))

stopifnot(near(expected_score(0), 0.5), near(expected_score(400), 10 / 11))
stopifnot(near(expected_score(c(0, 200), "normal"), c(0.5, pnorm(1))))
stopifnot(near(expected_score(c(-1000, 200, 1000), "linear"), c(0, 0.75, 1)))
stopifnot(near(expected_score(400, "bradley_terry"), 10 / 11))
stopifnot(fails(expected_score("a")), fails(expected_score(1, scale = -1)))

res <- data.frame(
  home = c("A", "B", "A"), away = c("B", "C", "C"),
  home_goals = c(1, 0, 2), away_goals = c(0, 0, 2)
)
rr <- run_ratings(res)
stopifnot(near(sum(rr$ratings), 4500), nrow(rr$history) == 3L)
stopifnot(all(rr$history$competition == "league"), near(rr$history$delta[1], 20 * (1 - e_home)))
stopifnot(near(rr$ratings[["A"]], rr$history$home_after[3]))
res$competition <- c("cup", "friendly", "tournament")
rr2 <- run_ratings(res, home_adv = 0)
stopifnot(near(rr2$history$delta[1], 15), identical(rr2$history$competition, res$competition))
stopifnot(fails(run_ratings(res, init = "x")))

r <- c(a = 1600, b = 1400)
stopifnot(identical(rating_decay(r, 10, "none"), r))
stopifnot(near(rating_decay(r, 10, "linear"), c(1590, 1410)))
stopifnot(near(rating_decay(r, 2, "exponential"), 1500 + c(100, -100) * 0.99^2))
stopifnot(near(rating_decay(r, c(59, 60), "step"), c(1570, 1460)))
stopifnot(near(rating_decay(r, 60, "floor"), c(1540, 1400)))
stopifnot(near(rating_decay(r, 500, "linear"), c(1500, 1500)))
stopifnot(identical(names(rating_decay(r, 1)), c("a", "b")))
stopifnot(fails(rating_decay(r, c(1, 2, 3))))

ex <- rating_extremes(rr$history)
stopifnot(identical(ex$team, c("A", "B", "C")))
stopifnot(near(ex$peak[1], max(rr$history$home_after[c(1, 3)])), ex$peak_game[1] %in% c(1, 3))
stopifnot(near(ex$trough[2], rr$history$home_after[2]), ex$trough_game[2] == 2)
stopifnot(ex$latest_game[2] == 2, ex$latest_game[3] == 3)
stopifnot(near(ex$latest[3], rr$history$away_after[3]))
