raw = c("<p>Visit https://ex.org now, 24/7!</p>", "a  b")
cl = cleanText(raw)
stopifnot(identical(as.vector(cl), c("Visit now", "a b")))
stopifnot(identical(attr(cl, "removed"),
  c(tags = 2L, urls = 1L, digits = 2L, punct = 3L, space = 3L)))
c2 = cleanText("x <b>y</b> 42", steps = c("digits", "tags"), replacement = "")
stopifnot(identical(as.vector(c2), "x y "))
stopifnot(identical(names(attr(c2, "removed")), c("digits", "tags")))
stopifnot(identical(as.vector(cleanText("a , b", steps = "punct", replacement = "")), "a  b"))

stopifnot(identical(wordNgrams(c("a", "b", "c")), c("a b", "b c")))
stopifnot(identical(wordNgrams(c("a", "b", "c"), n = 3L, sep = "_"), "a_b_c"))
stopifnot(identical(wordNgrams("a", n = 2L), character()))

stopifnot(identical(charNgrams("ab", n = 2L), c("_a", "ab", "b_")))
stopifnot(identical(charNgrams("abcd", n = 3L, pad = ""), c("abc", "bcd")))
stopifnot(identical(charNgrams("a", n = 3L, pad = ""), character()))

k = kwic(c("one two key three four five", "no match", "key end"), "^key$", before = 2L)
stopifnot(identical(k$doc, c(1L, 3L)), identical(k$position, c(3L, 1L)))
stopifnot(identical(k$left, c("one two", "")), identical(k$right, c("three four", "end")))
k2 = kwic("a b KEY c d", "^key$", before = 1L, after = 0L, ignoreCase = TRUE)
stopifnot(identical(k2$left, "b"), identical(k2$right, ""), identical(k2$keyword, "KEY"))
stopifnot(nrow(kwic("abc", "zzz")) == 0L)
stopifnot(inherits(tryCatch(kwic("a", "a", before = -1L), error = identity), "error"))

toks = list(d1 = c("b", "a", "b"), d2 = c("c", "b"))
tm = termMatrix(toks)
stopifnot(identical(dim(tm), c(2L, 3L)), identical(colnames(tm), c("a", "b", "c")))
stopifnot(tm["d1", "b"] == 2, tm["d2", "a"] == 0)
stopifnot(identical(colnames(termMatrix(toks, minCount = 2L)), "b"))
stopifnot(identical(unname(termMatrix(toks, "binary")["d1", ]), c(1, 1, 0)))
stopifnot(isTRUE(all.equal(unname(termMatrix(toks, "tf")["d1", ]), c(1 / 3, 2 / 3, 0))))
ti = termMatrix(toks, "tfidf")
stopifnot(ti["d1", "b"] == 0, isTRUE(all.equal(ti["d2", "c"], 0.5 * log(2))))
