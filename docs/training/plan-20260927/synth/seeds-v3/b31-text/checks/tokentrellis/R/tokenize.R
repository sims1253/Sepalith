r = tokenRules()
stopifnot(identical(names(r), c("url", "number", "word", "punct")))
stopifnot(grepl(r$number, "3.14", perl = TRUE), !grepl(r$word, "123", perl = TRUE))

ms = matchSpans("ab cd", "[a-z]+", "word")
stopifnot(identical(ms$start, c(1L, 4L)), identical(ms$end, c(2L, 5L)))
stopifnot(nrow(matchSpans("ab", "[0-9]", "number")) == 0L)

t1 = tokenizeOne("See https://ex.org/x, it's 3.5 Times!")
stopifnot(identical(t1$token, c("See", "https://ex.org/x", ",", "it's", "3.5", "Times", "!")))
stopifnot(identical(t1$type, c("word", "url", "punct", "word", "number", "word", "punct")))
t2 = tokenizeOne("Go 42 now.", rules = c("word", "punct"), lower = TRUE)
stopifnot(identical(t2$token, c("go", "now", ".")))
t3 = tokenizeOne("a1", rules = "number")
stopifnot(identical(t3$token, "1"), identical(t3$start, 2L))
stopifnot(nrow(tokenizeOne("")) == 0L)

tk = tokenize(c("Hi there.", NA, "x 2"))
stopifnot(identical(tk$doc, c(1L, 1L, 1L, 3L, 3L)), identical(tk$id[4], "3"))
stopifnot(identical(tk$type, c("word", "word", "punct", "word", "number")))
stopifnot(identical(tokenize("A b", lower = TRUE)$token, c("a", "b")))
td = tokenize(c(d1 = "Hi, you.", d2 = "ok!"), drop = "punct")
stopifnot(identical(td$token, c("Hi", "you", "ok")), identical(td$id, c("d1", "d1", "d2")))
stopifnot(inherits(tryCatch(tokenize(1), error = identity), "error"))

doc = c("One two.  Three four five! Six?\nSeven", "  ")
stopifnot(identical(countUnits(doc, "word"), c(7L, 0L)))
stopifnot(identical(countUnits(doc, "sentence"), c(4L, 0L)))
stopifnot(identical(countUnits(doc, "line"), c(2L, 1L)))
stopifnot(identical(countUnits(c("ab c", NA), "char"), c(3L, 0L)))
stopifnot(identical(countUnits(c("p1 a\nb\n\n  p2\n \np3", "x"), "paragraph"), c(3L, 1L)))
stopifnot(inherits(tryCatch(countUnits(1), error = identity), "error"))

ts = tokenSummary(tk)
stopifnot(ts$nTokens == 5L, ts$nTypes == 5L, ts$typeTokenRatio == 1)
stopifnot(identical(ts$byType, c(url = 0L, number = 1L, word = 3L, punct = 1L)))
stopifnot(is.na(tokenSummary(tk[0, ])$meanLength), is.na(tokenSummary(tk[0, ])$longest))
stopifnot(identical(ts$longest, "there"))
