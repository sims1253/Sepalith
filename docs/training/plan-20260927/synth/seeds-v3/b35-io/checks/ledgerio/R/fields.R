ledger <- data.frame(entry_id = 1:3, posted = as.Date("2026-04-01") + 0:2,
  account = c("cash", "bank", "cash"), amount = c(10, -2.5, 0), currency = c("EUR", "USD", "EUR"),
  memo = c("x|y", "", "line\nbreak"), stringsAsFactors = FALSE)
lines <- encode_records(ledger)
stopifnot(identical(lines[1], "000001|20260401|CASH|+1000|EUR|x%7Cy"))
stopifnot(identical(lines[2], "000002|20260402|BANK|-250|USD|"))
stopifnot(identical(encode_records(ledger[1, ], sep = ";"),
  "000001;20260401;CASH;+1000;EUR;x%7Cy"))
stopifnot(identical(encode_records(ledger[0, ]), character()))
msg <- tryCatch(encode_records(ledger[1:4]), error = conditionMessage)
stopifnot(identical(msg, "Column `currency` is required."))

back <- decode_records(lines)
stopifnot(identical(back$entry_id, 1:3), identical(back$posted, ledger$posted))
stopifnot(identical(back$amount, ledger$amount), identical(back$currency, ledger$currency))
stopifnot(identical(back$memo, c("x|y", NA, "line\nbreak")))
stopifnot(nrow(decode_records(character())) == 0)
msg <- tryCatch(decode_records(c(lines[1], "1|2|3")), error = conditionMessage)
stopifnot(identical(msg, "Line 2 has 3 fields, expected 6."))

path <- tempfile(fileext = ".txt")
stopifnot(identical(write_ledger_lines(ledger, path), path))
txt <- readLines(path)
stopifnot(identical(txt[1:3], c("#ledgerio lines v1",
  "#fields: entry_id|posted|account|amount|currency|memo", "#records: 3")), length(txt) == 6)
round <- read_ledger_lines(path)
stopifnot(identical(round$account, ledger$account), identical(round$memo[3], "line\nbreak"))
write_ledger_lines(ledger, path, sep = ";")
stopifnot(identical(read_ledger_lines(path, sep = ";")$amount, ledger$amount))
msg <- tryCatch(read_ledger_lines(path), error = conditionMessage)
stopifnot(grepl("has unexpected fields", msg))
writeLines(txt[1:5], path)
msg <- tryCatch(read_ledger_lines(path), error = conditionMessage)
stopifnot(grepl("is truncated or has extra lines", msg))
writeLines(c("nope", txt[2:3]), path)
msg <- tryCatch(read_ledger_lines(path), error = conditionMessage)
stopifnot(grepl("is not a ledgerio lines file", msg))
unlink(path)
