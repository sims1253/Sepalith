dir <- tempfile("manifest")
dir.create(file.path(dir, "sub"), recursive = TRUE)
writeLines(c("a", "b"), file.path(dir, "one.CSV"))
writeLines("ccc", file.path(dir, "sub", "two.dcf"))

m <- build_manifest(dir)
stopifnot(identical(m$file, c("one.CSV", "sub/two.dcf")), identical(m$format, c("csv", "dcf")))
stopifnot(identical(m$bytes, c(4, 4)), all(nchar(m$md5) == 32))
stopifnot(all(grepl("^\\d{4}-\\d{2}-\\d{2}T", m$modified)))
stopifnot(identical(build_manifest(dir, recursive = FALSE)$file, "one.CSV"))
stopifnot(identical(build_manifest(dir, pattern = "dcf$")$file, "sub/two.dcf"))
msg <- tryCatch(build_manifest(file.path(dir, "zz")), error = conditionMessage)
stopifnot(grepl("does not exist", msg))

stopifnot(identical(manifest_json_value("{\"a\":\"x\",\"b\":3}", "b"), "3"))
stopifnot(identical(manifest_json_value("{\"a\":\"x\",\"b\":3}", "a"), "x"))
msg <- tryCatch(manifest_json_value(c("{\"a\":1}", "{}"), "a"), error = conditionMessage)
stopifnot(identical(msg, "Manifest field `a` is missing on some lines."))

for (fmt in c("csv", "tsv", "dcf", "json")) {
  out <- tempfile(fileext = paste0(".", fmt))
  stopifnot(identical(write_manifest(m, out, format = fmt), out))
  back <- read_manifest(out, format = fmt)
  stopifnot(identical(back$file, m$file), identical(back$bytes, m$bytes))
  stopifnot(identical(back$md5, m$md5), identical(back$modified, m$modified))
  unlink(out)
}

v <- verify_manifest(m, dir)
stopifnot(identical(v$status, c("ok", "ok")))
Sys.setFileTime(file.path(dir, "one.CSV"), as.POSIXct("2020-01-01 00:00:00"))
stopifnot(identical(verify_manifest(m, dir)$status, c("touched", "ok")))
msg <- tryCatch(read_manifest(file.path(dir, "nope.csv")), error = conditionMessage)
stopifnot(grepl("does not exist", msg))
writeLines(c("a", "z"), file.path(dir, "one.CSV"))
writeLines("cccc", file.path(dir, "sub", "two.dcf"))
stopifnot(identical(verify_manifest(m, dir)$status, c("checksum", "size")))
unlink(file.path(dir, "one.CSV"))
stopifnot(identical(verify_manifest(m, dir)$status, c("missing", "size")))

writeLines("new", file.path(dir, "three.tsv"))
m2 <- build_manifest(dir)
d <- diff_manifests(m, m2)
stopifnot(identical(d$added, "three.tsv"), identical(d$removed, "one.CSV"))
stopifnot(identical(d$changed, "sub/two.dcf"), length(d$unchanged) == 0, length(d$renamed) == 0)
same <- diff_manifests(m2, m2)
stopifnot(length(same$added) == 0, length(same$removed) == 0, length(same$changed) == 0)
stopifnot(identical(same$unchanged, m2$file))
file.rename(file.path(dir, "three.tsv"), file.path(dir, "four.tsv"))
writeLines("extra", file.path(dir, "five.csv"))
d <- diff_manifests(m2, build_manifest(dir))
stopifnot(identical(d$renamed, "four.tsv"), identical(d$added, "five.csv"))
stopifnot(length(d$removed) == 0, identical(d$unchanged, "sub/two.dcf"))
unlink(dir, recursive = TRUE)
