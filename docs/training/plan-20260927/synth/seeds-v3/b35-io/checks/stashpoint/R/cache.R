setup = function() {
  for (k in c("k1", "k2", "k3")) cachePut(k, rnorm(c(k1 = 50, k2 = 300, k3 = 100)[[k]]), dir)
  idx = cacheIndexRead(dir)
  idx$created = c("2026-01-01T00:00:00", "2026-01-03T00:00:00", "2026-01-02T00:00:00")
  idx$accessed = c("2026-02-03T00:00:00", "2026-02-01T00:00:00", "2026-02-02T00:00:00")
  idx$hits = c(5L, 7L, 1L)
  cacheIndexWrite(idx, dir)
  sum(idx$bytes)
}
total = setup()
stopifnot(identical(cachePrune(dir, maxBytes = total - 1), "k1"))
stopifnot(identical(cacheIndexRead(dir)$key, c("k2", "k3")))
stopifnot(identical(cachePrune(dir, maxBytes = 0), c("k3", "k2")), length(cachePrune(dir, 0)) == 0)
total = setup()
stopifnot(identical(cachePrune(dir, total - 1, policy = "stale"), "k2"))
total = setup()
stopifnot(identical(cachePrune(dir, total - 1, policy = "largest"), "k2"))
total = setup()
stopifnot(identical(cachePrune(dir, total - 1, policy = "unused"), "k3"))
msg = tryCatch(cachePrune(dir, -1), error = conditionMessage)
stopifnot(identical(msg, "`maxBytes` must be a single non-negative number."))
