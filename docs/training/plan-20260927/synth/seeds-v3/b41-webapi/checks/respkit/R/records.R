old <- data.frame(id = 1:3, name = c("a", "b", "c"))
new <- data.frame(id = c(2L, 3L, 4L), name = c("b", "C", "d"))
d <- records.diff(old, new)
stopifnot(identical(d$added$id, 4L), identical(d$removed$id, 1L), identical(d$changed$id, 3L))
stopifnot(identical(d$changed$name, "C"))
d0 <- records.diff(old, old)
stopifnot(nrow(d0$added) == 0L, nrow(d0$removed) == 0L, nrow(d0$changed) == 0L)
stopifnot(inherits(try(records.diff(old, new, "key"), silent = TRUE), "try-error"))
