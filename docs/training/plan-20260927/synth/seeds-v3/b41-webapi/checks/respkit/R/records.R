a <- unwrap.envelope(list(data = list(1, 2), meta = list(total = 10)), "data")
stopifnot(identical(a, list(items = list(1, 2), total = 10L)))
b <- unwrap.envelope(list(results = list(1), count = 3), "results")
stopifnot(identical(b$items, list(1)), identical(b$total, 3L))
cc <- unwrap.envelope(list(items = list(), total_count = 0), "items")
stopifnot(identical(cc$items, list()), identical(cc$total, 0L))
v <- unwrap.envelope(list(value = list("x")), "value")
stopifnot(identical(v$items, list("x")), is.na(v$total))
stopifnot(identical(unwrap.envelope(list(), "data")$items, list()))
n1 <- unwrap.envelope(list(list(id = 1), list(id = 2)), "none")
stopifnot(length(n1$items) == 2L, identical(n1$total, 2L))
n2 <- unwrap.envelope(list(id = 1), "none")
stopifnot(identical(n2$items, list(list(id = 1))), identical(n2$total, 1L))

f <- flatten.record(list(id = 1, owner = list(login = "a", site = list(url = "u")),
  tags = list("x", "y"), refs = list(list(a = 1), list(a = 2)), note = NULL, v = c(1, 2)))
stopifnot(identical(names(f), c("id", "owner.login", "owner.site.url", "tags", "refs", "note",
  "v")))
stopifnot(identical(f$tags, "x,y"), identical(f$refs, 2L), is.na(f$note), identical(f$v, "1,2"))
stopifnot(identical(names(flatten.record(list(a = list(b = 1)), sep = "_")), "a_b"))

