hexOf = function(s) paste(as.character(charToRaw(s)), collapse = "")
for (drop in c("id", "createdAt", "direction", "sortKey", "version")) {
  all = c(id = "1", createdAt = "0", direction = "after", sortKey = "k", version = "1")
  keep = all[names(all) != drop]
  bad = hexOf(paste(paste0(names(keep), "=", keep), collapse = ";"))
  msg = tryCatch(decodeCursor(bad), error = conditionMessage)
  stopifnot(identical(msg, sprintf("Cursor field `%s` is missing.", drop)))
}

