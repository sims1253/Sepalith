fails <- function(expr) inherits(try(expr, silent = TRUE), "try-error")

stopifnot(identical(check_flag("a", "x"), "a"), is.null(check_flag(NULL, "x", allow_null = TRUE)))
stopifnot(fails(check_flag(NULL, "x")), fails(check_flag("", "x", "string")))
stopifnot(identical(check_flag(3L, "x", "count"), 3L), fails(check_flag(-1, "x", "count")))
stopifnot(fails(check_flag(1.5, "x", "count")))
stopifnot(isTRUE(check_flag(TRUE, "x", "switch")), fails(check_flag(NA, "x", "switch")))
stopifnot(identical(check_flag("a", "x", "choice", c("a", "b")), "a"))
stopifnot(fails(check_flag("c", "x", "choice", c("a", "b"))))
stopifnot(identical(check_flag(tempdir(), "x", "dir"), tempdir()))
stopifnot(fails(check_flag(file.path(tempdir(), "no-such-dir"), "x", "dir")))

src <- tempfile("src")
dir.create(src)
opts <- list(source = src, dest = file.path(tempdir(), "dst"), keep = 3L,
             compress = "gzip", dry_run = FALSE, verbose = TRUE)
stopifnot(identical(validate_backup_args(opts), opts))
with_opt <- function(...) modifyList(opts, list(...))
stopifnot(fails(validate_backup_args(with_opt(source = file.path(src, "nope")))))
stopifnot(fails(validate_backup_args(with_opt(dest = "/no/such/dir/x"))))
stopifnot(fails(validate_backup_args(with_opt(keep = 0L))))
stopifnot(fails(validate_backup_args(with_opt(compress = "zip"))))
stopifnot(fails(validate_backup_args(with_opt(dry_run = NA))))
stopifnot(fails(validate_backup_args(with_opt(verbose = "yes"))))
stopifnot(fails(validate_backup_args(with_opt(dest = src))))

o <- list(keep = 5, ratio = 0.5, name = NULL)
stopifnot(identical(check_flag_ranges(o, c(keep = 1, name = 0), c(ratio = 1)), o))
msg <- tryCatch(check_flag_ranges(o, lower = c(keep = 6)), error = conditionMessage)
stopifnot(identical(msg, "Flag `--keep` must be at least 6, not 5."))
msg <- tryCatch(check_flag_ranges(o, upper = c(ratio = 0.25)), error = conditionMessage)
stopifnot(identical(msg, "Flag `--ratio` must be at most 0.25, not 0.5."))

r <- list(a = TRUE, b = FALSE, c = "x")
stopifnot(identical(check_flag_relations(r, list(c("a", "b")), list(c("a", "c"))), r))
stopifnot(fails(check_flag_relations(r, conflicts = list(c("a", "c")))))
stopifnot(fails(check_flag_relations(r, requires = list(c("a", "b")))))

stopifnot(identical(check_required_flags(list(a = 1), "a"), list(a = 1)))
msg <- tryCatch(check_required_flags(list(a = 1), c("a", "b", "c")), error = conditionMessage)
stopifnot(grepl("`--b`, `--c`", msg, fixed = TRUE))

