stopifnot(identical(render.items(items, "latex")[3], "  \\item \\textbf{n\\_rows}: 4"))
stopifnot(identical(render.items(items, "plain"), c("  mean  : 2.0", "  n_rows: 4")))

df = data.frame(g = c("a", "b"), n = c(1L, 22L))
stopifnot(identical(render.table(df), c("| g | n |", "|---|---|", "| a |  1 |", "| b | 22 |")))
stopifnot(identical(render.table(df, "html")[3], "<tr><td>a</td><td> 1</td></tr>"))
stopifnot(identical(render.table(df, "latex")[c(1, 2)], c("\\begin{tabular}{ll}", "g & n \\\\")))
stopifnot(identical(render.table(df[1, ], "plain"), c("g  n", "a  1")))

