x <- c(1, 2, NA, 6)
stopifnot(as.numeric(wrenMean(x)) == 3, attr(wrenMean(x), "n") == 3L)
stopifnot(is.na(wrenMean(x, naRm = FALSE)), is.na(wrenMean(x, minN = 4L)))
stopifnot(inherits(try(wrenMean("a"), silent = TRUE), "try-error"))
stopifnot(inherits(try(wrenMean(1, minN = -1), silent = TRUE), "try-error"))
stopifnot(as.numeric(wrenMedian(x)) == 2, is.na(wrenMedian(numeric())))
stopifnot(inherits(try(wrenMedian(TRUE), silent = TRUE), "try-error"))
stopifnot(all.equal(as.numeric(wrenSd(x)), stats::sd(c(1, 2, 6))), is.na(wrenSd(1)))
stopifnot(attr(wrenSd(1), "n") == 1L)
stopifnot(inherits(try(wrenSd(1, minN = "a"), silent = TRUE), "try-error"))
stopifnot(as.numeric(wrenIqr(c(1, 2, 3, 4, 5))) == 2, is.na(wrenIqr(c(NA, 1))))
stopifnot(inherits(try(wrenIqr(1, minN = 1:2), silent = TRUE), "try-error"))
stopifnot(inherits(try(wrenMedian(1, minN = NA), silent = TRUE), "try-error"))

stopifnot(identical(statFunction("mean"), wrenMean), identical(statFunction("median"), wrenMedian))
stopifnot(identical(statFunction("sd"), wrenSd), identical(statFunction("iqr"), wrenIqr))
stopifnot(inherits(try(statFunction("max"), silent = TRUE), "try-error"))

df <- data.frame(a = c(1, 2, 3, NA), b = c(-1, 1, 0, 0), k = c("x", "x", "y", "y"))
dc <- describeColumns(df, c("a", "b"))
stopifnot(identical(dc$n, c(3L, 4L)), identical(dc$mean, c(2, 0)), identical(dc$median, c(2, 0)))
stopifnot(identical(dc$sd[1], 1), identical(dc$iqr[1], 1), identical(dc$cv, c(0.5, NA)))
stopifnot(inherits(try(describeColumns(df, "zz"), silent = TRUE), "try-error"))

gs <- groupStats(df, "k", "b")
stopifnot(identical(dimnames(gs), list(c("x", "y"), c("n", "mean", "median", "sd", "iqr"))))
stopifnot(identical(unname(gs[, "n"]), c(2, 2)))
stopifnot(inherits(try(groupStats(df, "k", "zz"), silent = TRUE), "try-error"))
stopifnot(gs["x", "mean"] == 0, gs["y", "sd"] == 0, gs["x", "iqr"] == 1)
stopifnot(is.na(groupStats(df, "k", "a", "sd")["y", "sd"]))

stopifnot(identical(attr(wrenMean(x), "missing"), 1L), attr(wrenMedian(x), "missing") == 1L)
stopifnot(as.numeric(wrenMean(c(1, 2, 2), digits = 2)) == 1.67)
stopifnot(as.numeric(wrenSd(c(1, 2, 4), digits = 1)) == 1.5, attr(wrenIqr(x), "missing") == 1L)
stopifnot(as.numeric(wrenMedian(c(1.26, 3), digits = 1)) == 2.1)
stopifnot(as.numeric(wrenIqr(c(0, 1.25), digits = 1)) == 0.6)
