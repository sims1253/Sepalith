stopifnot(identical(currency_spec("EUR")$position, "suffix"))
stopifnot(identical(currency_spec("USD")$symbol, "$"))
stopifnot(identical(currency_spec("GBP")$sep, " "))
stopifnot(currency_spec("JPY")$digits == 0L)
stopifnot(identical(currency_spec("CHF")$big_mark, "'"))

rates <- c(EUR = 1, USD = 1.1, JPY = 160)
stopifnot(isTRUE(check_currency_args(1, "EUR", rates)))
stopifnot(inherits(try(check_currency_args("1", "EUR", rates), silent = TRUE), "try-error"))
stopifnot(inherits(try(check_currency_args(1, c("A", "B"), rates), silent = TRUE), "try-error"))
stopifnot(inherits(try(check_currency_args(1, "EUR", c(1, 2)), silent = TRUE), "try-error"))
stopifnot(inherits(try(check_currency_args(1, "EUR", c(EUR = 0)), silent = TRUE), "try-error"))

stopifnot(all.equal(round_amount(c(2.5, -2.5), 0), c(3, -3)))
stopifnot(all.equal(round_amount(c(2.5, 3.5), 0, "half_even"), c(2, 4)))
stopifnot(all.equal(round_amount(c(1.29, -1.29), 1, "down"), c(1.2, -1.2)))
stopifnot(all.equal(round_amount(c(1.21, -1.21), 1, "up"), c(1.3, -1.3)))

stopifnot(identical(fmt_currency(1234.5), "1.234,50 EUR"))
stopifnot(identical(fmt_currency(-1234.5, "USD"), "-$1,234.50"))
stopifnot(identical(fmt_currency(c(-5, NA), "JPY", accounting = TRUE), c("(JPY 5)", "")))
stopifnot(identical(fmt_currency(1e6, "CHF"), "CHF 1'000'000.00"))

dl <- fmt_currency_delta(c(10, -2.5, 0, NA), "USD")
stopifnot(identical(dl, c("+$10.00", "-$2.50", "no change", NA)))
stopifnot(identical(fmt_currency_delta(-1, "GBP", loss_mark = "down "), "down GBP 1.00"))

stopifnot(all.equal(convert_amount(100, "EUR", "USD", rates), 110))
stopifnot(all.equal(convert_amount(160, "JPY", "USD", rates), 1.1))
stopifnot(inherits(try(convert_amount(1, "EUR", "GBP", rates), silent = TRUE), "try-error"))

ct <- currency_totals(c(10, 30, 60, NA), c("a", "b", "c", "a"), "USD")
stopifnot(identical(names(ct), c("group", "total", "share", "label")))
stopifnot(identical(ct$group, c("c", "b", "a")), all.equal(ct$share, c(0.6, 0.3, 0.1)))
stopifnot(identical(ct$label[1], "$60.00 (60.0%)"))
stopifnot(inherits(try(currency_totals(1, c("a", "b")), silent = TRUE), "try-error"))

