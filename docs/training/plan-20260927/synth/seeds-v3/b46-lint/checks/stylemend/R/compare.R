old <- c("x = 1", "y <- 2", "z <- 3")
new <- c("x <- 1", "y <- 2", "w <- 0", "z <- 3")

d <- style.diff(old, new)
stopifnot(identical(d$op, c("-", "+", " ", "+", " ")))
stopifnot(identical(d$old, c(1L, NA, 2L, NA, 3L)), identical(d$new, c(NA, 1L, 2L, 3L, 4L)))
stopifnot(identical(d$text[1:2], c("x = 1", "x <- 1")))
stopifnot(identical(style.diff(old, old)$op, rep(" ", 3)))
stopifnot(nrow(style.diff(character(), character())) == 0L)
stopifnot(identical(style.diff(character(), "a")$op, "+"))
stopifnot(identical(style.diff("a", character())$op, "-"))

u <- render.diff(old, new)
stopifnot(identical(u[1:2], c("--- before", "+++ after")))
stopifnot(identical(u[3:4], c("-x = 1", "+x <- 1")))
stopifnot(length(u) == 7L, identical(u[5], " y <- 2"))
sd <- render.diff(old, new, "side")
stopifnot(identical(sd[1], "x = 1  - "), identical(sd[2], "       + x <- 1"))
stopifnot(identical(sd[3], "y <- 2 | y <- 2"))
il <- render.diff(old, new, "inline")
stopifnot(identical(il, c("   1 - x = 1", "   1 + x <- 1", "   3 + w <- 0")))
stopifnot(identical(render.diff(old, old, "inline"), "no changes"))
stopifnot(identical(render.diff(old, new, "stat"), "2 insertions(+), 1 deletions(-)"))

cs <- change.summary(c("a <- 1; b <- 2 ", "", "# x; y", strrep("z", 90)), c("a <- 1", "b <- 2"))
stopifnot(identical(cs$measure, c("lines", "blank", "trailing", "long", "semicolons", "chars")))
stopifnot(identical(cs$before, c(4L, 1L, 1L, 1L, 1L, 111L)))
stopifnot(identical(cs$after, c(2L, 0L, 0L, 0L, 0L, 12L)))
stopifnot(identical(cs$delta, cs$after - cs$before))
stopifnot(change.summary(strrep("z", 90), "", width = 100L)$before[4] == 0L)

trim <- function(text) list(after = sub(" +$", "", text))
eqs <- function(text) list(after = gsub(" = ", " <- ", text, fixed = TRUE))
brk <- function(text) list(after = paste0(text, "("))
ck <- check.fixer(trim, c("x <- 1  ", "y"))
stopifnot(ck$parses, ck$same.code, ck$idempotent, ck$changed == 2L)
ck2 <- check.fixer(eqs, "x = 1")
stopifnot(ck2$parses, !ck2$same.code, ck2$idempotent, ck2$changed == 2L)
ck3 <- check.fixer(brk, "x")
stopifnot(!ck3$parses, !ck3$same.code, !ck3$idempotent)
head.fixer <- function(text, n) list(after = text[seq_len(n)])
stopifnot(check.fixer(head.fixer, c("a", "b"), n = 1L)$changed == 1L)

up <- function(text) list(after = toupper(text))
down <- function(text) list(after = tolower(text))
rt <- roundtrip.fixer(c("a", "B", "c"), up, down)
stopifnot(identical(rt$forward, c("A", "B", "C")), identical(rt$backward, c("a", "b", "c")))
stopifnot(rt$edits.forward == 4L, rt$edits.backward == 6L, !rt$restored, identical(rt$lost, 2L))
rt2 <- roundtrip.fixer(c("a", "b"), up, down)
stopifnot(rt2$restored, identical(rt2$lost, integer()))
