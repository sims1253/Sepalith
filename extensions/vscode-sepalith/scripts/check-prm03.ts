// PRM03 parity against the Python contract on TRAIN-derived golden fixtures
// (tests/fixtures/prm03-golden.json, built by build_prm03_fixtures.py):
// render (sha256 of the exact prompt text), output parse, generation-token
// validity, source-window selection, history diff spelling, and the editor
// builder reproducing TRAIN prompts from the rebuilt document state.
// Plain node, no vscode. Run: npm run check-prm03
import * as assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { parseOutput, promptContextFromJson, renderPrompt, validGenerationTokens } from '../src/prm03.ts';
import type { PromptContext } from '../src/prm03.ts';
import { buildEditorRequest, EditHistory, eventDiff, sha256Text } from '../src/prm03_context.ts';
import { selectSourceWindow } from '../src/prm03_select.ts';

interface RenderCase { id: string; variant: string; context_id: string; prompt_sha256: string; prompt_chars: number }
interface ParseCase { id: string; context_id: string; text: string; tokens?: number[]; valid_tokens?: boolean;
  expected: { status: string; operation: string | null; body: string[]; body_text: string; reason: string | null } }
interface SelectionResult { budget: number; expected: Record<string, number | boolean | string[]>; omissions: { side: string; start_line: number; end_line: number }[] }
interface SelectionCase { id: string; lines: string[]; region_start_line: number; region_end_line: number; results: SelectionResult[] }
interface HistoryCase { id: string; path: string; start: number; old: string[]; new: string[]; event_diff: string }
interface Fixture {
  counts: Record<string, number>;
  contexts: Record<string, PromptContext>;
  render: RenderCase[];
  parse: ParseCase[];
  selection: SelectionCase[];
  history: HistoryCase[];
}

const path = join(dirname(process.argv[1]), '..', 'tests', 'fixtures', 'prm03-golden.json');
// SAFETY: the fixture is generated by build_prm03_fixtures.py; every context is re-validated below.
const fixture = JSON.parse(readFileSync(path, 'utf8')) as Fixture;
const contexts = new Map<string, PromptContext>();
for (const [id, raw] of Object.entries(fixture.contexts)) contexts.set(id, promptContextFromJson(raw));

let rendered = 0;
for (const c of fixture.render) {
  const prompt = renderPrompt(contexts.get(c.context_id)!);
  assert.equal([...prompt].length, c.prompt_chars, `${c.id} (${c.variant}) prompt length in code points`);
  assert.equal(sha256Text(prompt), c.prompt_sha256, `${c.id} (${c.variant}) prompt bytes`);
  rendered++;
}
console.log(`PASS render parity: ${rendered}/${fixture.render.length} identical across ${new Set(fixture.render.map(c => c.variant)).size} variants`);

let parsed = 0;
let tokenChecks = 0;
for (const c of fixture.parse) {
  const actual = parseOutput(c.text, contexts.get(c.context_id)!);
  assert.deepEqual(actual, c.expected, `${c.id} parse`);
  parsed++;
  if (c.tokens) {
    assert.equal(validGenerationTokens(c.tokens), c.valid_tokens, `${c.id} token validity`);
    tokenChecks++;
  }
}
console.log(`PASS parse parity: ${parsed}/${fixture.parse.length} identical (${tokenChecks} census outputs with token validity)`);

let windows = 0;
for (const c of fixture.selection) {
  for (const r of c.results) {
    const { omissions, ...actual } = selectSourceWindow(c.lines, c.region_start_line, c.region_end_line, r.budget);
    assert.deepEqual(actual, r.expected, `${c.id} budget ${r.budget}`);
    assert.deepEqual(omissions, r.omissions, `${c.id} budget ${r.budget} omissions`);
    windows++;
  }
}
console.log(`PASS source-window parity: ${windows} windows identical`);

for (const c of fixture.history) assert.equal(eventDiff(c.path, c.start, c.old, c.new), c.event_diff, `${c.id} event_diff`);
console.log(`PASS history diff spelling: ${fixture.history.length}/${fixture.history.length} identical`);

// editor builder: the TRAIN document state (prefix + region + suffix, cursor) renders the TRAIN prompt
let rebuilt = 0;
let skipped = 0;
for (const c of fixture.render) {
  if (c.variant.startsWith('derived:')) continue;
  const ctx = contexts.get(c.context_id)!;
  if (ctx.region_old.length > 1) { skipped++; continue; } // the editor's region is one line
  const region = ctx.region_old.length ? ctx.region_old : [''];
  const lines = [...ctx.prefix, ...region, ...ctx.suffix_lines];
  const request = buildEditorRequest({
    lines, eol: ctx.document_eol === 'crlf' ? 'crlf' : 'lf', cursorLine: ctx.prefix.length,
    cursorUtf16: ctx.cursor.utf16_column ?? 0, path: ctx.path, uri: ctx.replacement_range.uri,
    version: ctx.replacement_range.document_version, contentSha256: ctx.replacement_range.content_sha256, history: ctx.history,
  });
  assert.equal(sha256Text(request.prompt), c.prompt_sha256, `${c.id} editor rebuild`);
  rebuilt++;
}
console.log(`PASS editor rebuild: ${rebuilt} TRAIN states render the TRAIN prompt (${skipped} multi-line regions skipped)`);

// history provider: typing bursts coalesce, commit when the cursor leaves, TRAIN diff spelling
{
  const h = new EditHistory('file:///w/R/f.R', () => 'R/f.R');
  let doc = ['f <- function(x) {', '  xlim <- par("usr")[1:2]', '  xpos <- xlim[1]', '}'];
  const edit = (line: number, text: string) => { const next = [...doc]; next[line] = text; h.observe(doc, next, 1); doc = next; };
  edit(1, '  xlim2 <- par("usr")[1:2]'.slice(0, 7) + ' <- par("usr")[1:2]');
  edit(1, '  xlim2 <- par("usr")[1:2]');
  h.cursorAt(1, doc);
  assert.deepEqual(h.events(), [], 'the line being edited is not history yet');
  h.cursorAt(2, doc);
  const [event] = h.events();
  assert.equal(event.event_diff, 'User edited "R/f.R":\n\n```diff\n@@ -2 +2 @@\n-  xlim <- par("usr")[1:2]\n+  xlim2 <- par("usr")[1:2]\n```');
  assert.deepEqual([event.old_text, event.new_text, event.range_utf16.start, event.range_utf16.end],
    ['  xlim <- par("usr")[1:2]', '  xlim2 <- par("usr")[1:2]', { line: 1, character: 0 }, { line: 1, character: 25 }]);
  // a pure line insertion is widened by its unchanged neighbour (TRAIN events always have both sides)
  const before = doc;
  doc = [...doc.slice(0, 3), '  ypos <- 1', ...doc.slice(3)];
  h.observe(before, doc, 2);
  h.cursorAt(0, doc);
  assert.equal(h.events()[0].event_diff, 'User edited "R/f.R":\n\n```diff\n@@ -3,1 +3,2 @@\n-  xpos <- xlim[1]\n+  xpos <- xlim[1]\n+  ypos <- 1\n```');
  assert.equal(h.events().length, 1, 'one event in the prompt');
  // an undone burst leaves no event; an edit elsewhere commits the previous burst
  const h2 = new EditHistory('u', () => 'R/g.R');
  const a = ['a', 'b', 'c'];
  h2.observe(a, ['a', 'B', 'c'], 1); h2.observe(['a', 'B', 'c'], a, 2); h2.cursorAt(2, a);
  assert.deepEqual(h2.events(), [], 'undone burst');
  h2.observe(a, ['A', 'b', 'c'], 3); h2.observe(['A', 'b', 'c'], ['A', 'b', 'C'], 4);
  assert.equal(h2.events()[0].new_text, 'A', 'edit two lines away commits the first burst');
  console.log('PASS history provider');
}
console.log('PRM03 golden parity checks passed');
