"""Generate the audit STATS.md from machine-written inputs only (no hand-typed counts).

    python -m sepalith.data.synth.report --data /mnt/e/.../SYNTH-v2 --profile profile.json \\
        [--probe receipts/SYNTH-v2-arm-a-probe.json] --out docs/.../synth/audit/STATS.md
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from collections import Counter

from sepalith.data.synth.profile import BUCKETS
from sepalith.data.synth.profile import bucket as profile_bucket


def pct(x: float | None) -> str:
    return "-" if x is None else f"{100 * x:.1f}%"


def table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return out + [""]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--profile", type=Path, required=True, help="profile.py output with train, v1 and v2 keys")
    parser.add_argument("--probe", type=Path, default=None)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    summary = json.loads((args.data / "build-summary.json").read_text())
    manifest_sha = hashlib.sha256((args.data / "manifest.json").read_bytes()).hexdigest()
    prof = json.loads(args.profile.read_text())
    # TRAIN first, then the SYNTH builds (the profile file has sorted keys)
    keys = ["train"] + sorted(k for k in prof if k != "train")
    names = ["TRAIN"] + [Path(k).parent.name for k in keys[1:]]
    stats = summary["stats"]
    lines = [f"# {args.data.name}: generated statistics", "",
             f"Generated by `sepalith.data.synth.report` from `{args.data}` "
             f"(manifest sha256 `{manifest_sha}`) and `{args.profile.name}`. Do not edit by hand.", ""]

    lines += ["## Counts", ""]
    lines += table(["family", "rows"], [[f, n] for f, n in sorted(stats["families"].items())])
    rule_rows = [[f, r, n] for f, rules in sorted(stats["rule"].items()) for r, n in sorted(rules.items())]
    lines += ["Cut type / rule:", ""] + table(["family", "rule", "rows"], rule_rows)
    det_rows = [[f, d, n] for f, ds in sorted(summary["determinacy"].items()) for d, n in sorted(ds.items())]
    lines += ["Determinacy class (finish_block):", ""] + table(["family", "class", "rows"], det_rows)
    beh = summary["behaviour"]
    beh_rows = [[f, b, n] for f, bs in sorted(beh["final_cases"].items()) for b, n in sorted(bs.items())]
    lines += [f"Behavioural evidence ({beh['meaning']}); seed files: `{json.dumps(beh['seed_files'])}`", ""]
    lines += table(["family", "evidence", "rows"], beh_rows)
    fb = stats.get("families", {}).get("finish_block", 0)
    lines += table(["finish_block flag", "rows", "share"],
                   [["full body", stats["full_body"], pct(stats["full_body"] / fb if fb else None)],
                    ["signature-line region", stats["signature_region"], pct(stats["signature_region"] / fb if fb else None)],
                    ["test file", stats["test_file"], pct(stats["test_file"] / fb if fb else None)]])
    div = stats["diversity"]
    lines += ["Diversity: " + ", ".join(f"{k} {v}" for k, v in div.items()), ""]

    lines += ["## Verification (reported separately)", ""]
    pv = summary["protocol_verification"]
    lines += [f"- Mechanical checks ({pv['meaning']}): {pv['passed']} / {pv['candidates']} "
              f"= {pct(pv['mechanical_pass_rate'])}. Failures: `{json.dumps(pv['failures'])}`.",
              "- Determinacy: the class table above. The classes are *proxies* (generator filters), not proofs "
              "that a completion is determined; known holes are listed in the audit README and measured in "
              "receipts/SYNTH-v2-determinacy-holes.json.",
              "- Behavioural evidence: the table above. `entered` means the unit's body executed during a passing "
              "base-R check script; it does not mean the check asserted the target's behaviour.", ""]

    for family in ("finish_block", "roxygen_drafting"):
        present = [k for k in keys if family in prof[k]]
        cols = [names[keys.index(k)] for k in present]
        get = lambda k, f=family: prof[k][f]  # noqa: E731
        lines += [f"## Distribution vs TRAIN: {family}", ""]
        metric_rows = [
            ["cases", *[get(k)["cases"] for k in present]],
            ["median target lines", *[get(k)["median_target_lines"] for k in present]],
            ["target has a blank line", *[pct(get(k)["any_blank_line"]) for k in present]],
            ["target has a full-line comment", *[pct(get(k)["any_full_line_comment"]) for k in present]],
            ["target starts with a blank line", *[pct(get(k)["leading_blank_line"]) for k in present]],
            ["single `}` targets", *[get(k)["single_close_brace"] for k in present]],
            ["prefix without any blank line", *[pct(get(k)["prefix_without_blank_line"]) for k in present]],
        ]
        if family == "finish_block":
            metric_rows += [["full-body cut", *[pct(get(k)["full_body"]) for k in present]],
                            ["  of which signature-line region", *[pct(get(k)["full_body_signature_region"]) for k in present]],
                            ["  of which empty region", *[pct(get(k)["full_body_empty_region"]) for k in present]],
                            ["test file", *[pct(get(k)["test_file"]) for k in present]]]
        lines += table(["metric", *cols], metric_rows)
        bucket_names = [b for _, b in BUCKETS] + [">45"]
        lines += ["Target length buckets (lines):", ""]
        lines += table(["bucket", *cols], [[b, *[pct(get(k)["target_length_buckets"].get(b, 0)) for k in present]]
                                           for b in bucket_names])
        if family == "finish_block":
            lines += ["Blank line / full-line comment share inside each length bucket "
                      "(TRAIN's leading blank line removed):", ""]
            rows = []
            for b in bucket_names:
                cells = []
                for k in present:
                    entry = get(k)["by_bucket_blank_comment"].get(b)
                    cells.append(f"{pct(entry['blank'])} / {pct(entry['comment'])} (n={entry['cases']})"
                                 if entry else "-")
                rows.append([b, *cells])
            lines += table(["bucket", *cols], rows)
        if family == "roxygen_drafting":
            tags = sorted({t for k in present for t in get(k)["tag_frequency"]},
                          key=lambda t: -get(keys[0])["tag_frequency"].get(t, 0))
            lines += ["Tag frequency (share of blocks with the tag):", ""]
            lines += table(["tag", *cols], [[t, *[pct(get(k)["tag_frequency"].get(t, 0)) for k in present]]
                                            for t in tags if any(get(k)["tag_frequency"].get(t, 0) >= 0.01 for k in present)])
            lines += table(["tag orders", *cols],
                           [["distinct", *[get(k)["distinct_tag_orders"] for k in present]],
                            ["most common order share", *[pct(get(k)["top_tag_orders"][0][1] / get(k)["cases"])
                                                          for k in present]]])

    # Prompt geometry: finish_block prompts by packaging variant vs TRAIN.
    from sepalith.data.synth.profile import train_finish_geometry
    import statistics
    cases = [json.loads(x) for x in (args.data / "cases.jsonl").open(encoding="utf-8")]
    tokens = {json.loads(x)["id"]: json.loads(x)["prompt_token_count"]
              for x in (args.data / "train-token-rows.jsonl").open(encoding="utf-8")}
    finish = [c for c in cases if c["family"] == "finish_block"]

    def geo_row(label: str, pairs: list[tuple[int, int]]) -> list:
        if not pairs:
            return [label, 0, "-", "-", "-"]
        return [label, len(pairs), statistics.median(p for p, _ in pairs), statistics.median(t for _, t in pairs),
                pct(sum(p > 60 for p, _ in pairs) / len(pairs))]

    geo = [geo_row("TRAIN", train_finish_geometry()),
           geo_row("SYNTH all", [(len(c["context"]["prefix"]), tokens[c["row_id"]]) for c in finish])]
    for variant in sorted({c["meta"]["variant"] for c in finish}):
        geo.append(geo_row(f"SYNTH {variant}", [(len(c["context"]["prefix"]), tokens[c["row_id"]])
                                                for c in finish if c["meta"]["variant"] == variant]))
    sib = Counter(c["meta"]["variant"] for c in finish if c["meta"].get("determinacy") == "sibling")
    lines += ["## Prompt geometry (finish_block)", "",
              "The `file` variant shows the preceding file (siblings); when a cut fails the determinacy proxy in "
              "its first packaging, the generator retries it as `file` (finish_block.py, retry-with-file), so "
              "`file` dominates and prompts are longer than TRAIN's.", ""]
    lines += table(["prompts", "cases", "median prefix lines", "median prompt tokens", "prefix > 60 lines"], geo)
    lines += [f"`sibling` cases by variant: `{json.dumps(dict(sib))}`.", ""]

    # Masked structural overlap, retained set vs all verified candidates.
    def masked_row(ref: str) -> list:
        values = [c["meta"]["decontamination"][f"masked_{ref}_containment"] for c in cases]
        high = [c for c in cases if c["meta"]["decontamination"][f"masked_{ref}_containment"] >= 0.8]
        lengths = Counter(profile_bucket(len(c["region_new"])) for c in high)
        return [ref, len(values), sum(v >= 0.5 for v in values), len(high), sum(v >= 1.0 for v in values),
                json.dumps(dict(sorted(lengths.items())))]

    lines += ["Identifier-masked structural containment on the **retained** rows (candidate-level numbers are "
              "in the Decontamination section):", ""]
    lines += table(["reference", "rows", ">= 0.5", ">= 0.8", "= 1.0", "target lengths of >= 0.8 rows"],
                   [masked_row("train"), masked_row("dev")])

    lines += ["## Length shaping (finish_block)", "",
              "Bucket definition used by the shaping rules: SYNTH targets are counted raw (`len(region_new)`, "
              "including the restated signature line of signature-region cases); TRAIN targets are counted with "
              "their leading blank line removed (a TRAIN-only artefact, see receipts/DT-ws-nearmiss.json). "
              "Ratios of SYNTH share to TRAIN share under both TRAIN definitions:", ""]
    raw_train = prof["train"]["finish_block"]["target_length_buckets"]
    synth_share = summary["shaping"]["synth_share"]
    stripped = summary["shaping"]["train_share"]
    lines += table(["bucket", "SYNTH share", "TRAIN (leading blank stripped)", "ratio", "TRAIN (raw)", "ratio"],
                   [[b, pct(synth_share[b]), pct(stripped[b]), f"{synth_share[b] / stripped[b]:.2f}x",
                     pct(raw_train.get(b, 0)),
                     f"{synth_share[b] / raw_train[b]:.2f}x" if raw_train.get(b) else "-"] for b in synth_share])
    lines += ["```json", json.dumps(summary["shaping"], indent=1), "```", ""]
    lines += ["## Decontamination", ""]
    dc = summary["decontamination"]
    lines += table(["family:reason", "removed"], [[k, v] for k, v in sorted(dc["removed"].items())])
    lines += [f"Fingerprint: `{json.dumps(dc['fingerprint'])}`; thresholds (containment, longest run in tokens): "
              f"`{json.dumps(dc['thresholds'])}`.", "",
              "Identifier-masked structural containment (reported, not a filter; share of the edit span's masked "
              "12-grams found in the reference):", ""]
    lines += table(["reference", "cases", ">= 0.5", ">= 0.8", "= 1.0"],
                   [[ref, v["cases"], v.get(">=0.5", 0), v.get(">=0.8", 0), v.get("==1.0", 0)]
                    for ref, v in dc["masked_structural_containment"].items()])
    cpt = dict(dc["cpt_reference"] or {})
    files_with_hits = cpt.pop("seed_files_with_hits", {})
    cpt["seed_files_with_hits"] = len(files_with_hits)
    lines += [f"DEV reference: {dc['dev_reference']['files']} files, {dc['dev_reference']['documents_hashed']} strings "
              f"hashed. CPT reference (per-file hits in cpt-hits.json): `{json.dumps(cpt)}`. "
              f"Split file read: {dc['split_file_read']}.", ""]
    lines += ["## Rejections", ""] + table(["family:reason", "count"],
                                            [[k, v] for k, v in sorted(summary["generator_rejections"].items())])
    if args.probe and args.probe.exists():
        probe = json.loads(args.probe.read_text())
        lines += ["## Arm A probe (Q8_0, greedy, CPU)", ""]
        lines += table(["stratum", "exact", "cases", "mean reward"],
                       [[k, v["exact"], v["cases"], v["mean_reward"]] for k, v in probe["by_stratum"].items()])
        rows_now = hashlib.sha256((args.data / "train-token-rows.jsonl").read_bytes()).hexdigest()
        rows_probe = probe["data"]["train-token-rows.jsonl"]
        lines += [f"Probe bound to train-token-rows.jsonl sha256 `{rows_probe}`; current rows `{rows_now}` "
                  f"(identical: {rows_probe == rows_now}). The probe receipt's manifest hash predates later "
                  "metadata-only rebuilds; rows are the binding input.", ""]
        lines += [f"Sample seed {probe['sample']['seed']}, ids excluded from the audit sample: "
                  f"{probe['sample'].get('excluded_ids')}, overlap: {probe['sample'].get('overlap_with_excluded')}.", ""]
    args.out.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
